def to_px(x, z, size=PX, margin=0):
    s = (size - 2 * margin) / (2 * HALF)
    return margin + (x + HALF) * s, margin + (z + HALF) * s


def fbm(seed, n=N, octaves=5, base=6):
    rng = np.random.default_rng(seed)
    out = np.zeros((n, n))
    amp = 1.0
    total = 0.0
    for o in range(octaves):
        g = base * (2 ** o)
        grid = rng.random((g + 1, g + 1))
        img = Image.fromarray((grid * 255).astype(np.uint8)).resize((n, n), Image.BICUBIC)
        out += np.asarray(img, dtype=float) / 255.0 * amp
        total += amp
        amp *= 0.5
    return out / total - 0.5


def seg_dist(px, pz, a, b):
    ax, az = a
    bx, bz = b
    dx, dz = bx - ax, bz - az
    t = np.clip(((px - ax) * dx + (pz - az) * dz) / (dx * dx + dz * dz), 0, 1)
    return np.hypot(px - (ax + t * dx), pz - (az + t * dz))


# out を渡すと、生成器が使う途中の値 (X, Z, field, ridge, dists) も入れて返す
def terrain(lay, seed, n=N, out=None):
    xs = np.linspace(-HALF, HALF, n)
    X, Z = np.meshgrid(xs, xs)
    warp = fbm(seed + 1, octaves=4, base=4, n=n) * 500
    warp2 = fbm(seed + 2, octaves=4, base=4, n=n) * 500
    WX, WZ = X + warp, Z + warp2
    field = np.zeros_like(X)
    for (cx, cz), r, w in lay['land']:
        field += w * np.clip(1 - np.hypot(WX - cx, WZ - cz) / r, 0, None) ** 0.6
    if 'island' in lay:
        (cx, cz), r, w = lay['island']
        field += w * np.clip(1 - np.hypot(X + warp * 0.2 - cx, Z + warp2 * 0.2 - cz) / r, 0, None) ** 0.6
    for (cx, cz), r, w in lay['sea']:
        field -= w * np.clip(1 - np.hypot(WX - cx, WZ - cz) / r, 0, None) ** 0.7
    # 湖 (陸の中の小さな水)。揺らぎを小さくして形を保つ
    lake_noise = fbm(seed + 41, octaves=4, base=24, n=n)
    for (cx, cz), r in lay.get('lakes', []):
        d = np.hypot(X + warp * 0.15 - cx, Z + warp2 * 0.15 - cz) / r + lake_noise * 0.9
        field -= np.clip(1.15 - d, 0, None) * 2.5
    field += fbm(seed + 3, octaves=5, base=5, n=n) * 0.35
    edge = np.clip((np.maximum(abs(X), abs(Z)) - 1600) / 400, 0, 1)
    field -= edge * 1.2
    land = field > 0.18
    # 高さ: 岸からの近さ + 峰 + 揺らぎ
    height = np.clip(field - 0.18, 0, None) * 0.9 + fbm(seed + 4, octaves=6, base=8, n=n) * 0.12
    ridge = np.zeros_like(X)
    for a, b, w in lay['ridges']:
        d = seg_dist(WX * 0.3 + X * 0.7, WZ * 0.3 + Z * 0.7, a, b)
        ridge += w * np.clip(1 - d / 260, 0, None) ** 1.5 * (0.8 + fbm(seed + 5, octaves=5, base=10, n=n) * 1.4)
    height += ridge
    # 土地: ゆがめた距離で一番近い種
    best = np.full(X.shape, 1e9)
    region = np.zeros(X.shape, dtype=int)
    dists = []
    # 土地の境を波打たせる (C1 から。A〜C の案の絵は前のまま)
    if lay.get('wavy'):
        border_noise = [fbm(seed + 50 + k, octaves=4, base=8, n=n) for k in range(3)]
    else:
        border_noise = [np.zeros_like(X)] * 3
    for i, (_, (cx, cz)) in enumerate(lay['regions']):
        scale = 0.55 if lay['regions'][i][0] == 'start' else 1.0
        d = np.hypot(WX * 0.6 + X * 0.4 - cx, WZ * 0.6 + Z * 0.4 - cz) / (scale if scale else 1) + border_noise[i % 3] * 260
        dists.append(d)
        m = d < best
        best[m] = d[m]
        region[m] = i
    for i, (kind, _) in enumerate(lay['regions']):
        if kind == 'storm':
            height = np.where(region == i, height + 0.25, height)
        if kind == 'whale':
            height = np.where(region == i, height + 0.1, height)
    # 土地の中のムラ (湖のまわりの林・湿地・砂丘など)。ゆがめた円の中。種類ごとの印 (subs: [(種類, 印の配列)])
    subs = []
    sub_noise = fbm(seed + 42, octaves=5, base=10, n=n)
    for kind, (cx, cz), r in lay.get('subs', []):
        d = np.hypot(X + warp * 0.35 - cx, Z + warp2 * 0.35 - cz) / r + sub_noise * 1.4
        subs.append((kind, (d < 1) & land))
    if out is not None:
        out.update(X=X, Z=Z, field=field, ridge=ridge, dists=dists, subs=subs)
    return land, height, region


