#!/usr/bin/env python3
"""Write the shot scripts that check the five low-poly installs (docs/design/15_high_poly.md section 9).
    python tools/gen_lowpoly_five_shots.py            -> tools/shots/lp_<name>.txt
    ./gradlew runShots -Pscript=tools/shots/lp_<name>.txt
Pictures land in run/shots/lp_<name>/shots/lp_<name>/ (copy the ones to keep to docs/review/previews/).
Poses use `cmd skyabyss dev anim <selector> <action>` and shots a few ticks apart."""
import os

HEAD = """# Generated by tools/gen_lowpoly_five_shots.py: {title}
world shots flat
size 1280 720
timeout 900
render 8
clouds off
cmd skyabyss cinematic stop
cmd time set noon
cmd weather clear
cmd gamemode spectator
cmd fill -30 -61 -30 30 -61 30 minecraft:smooth_basalt destroy
cmd kill @e[type=!minecraft:player,distance=..80]
hud off
"""


def cam(x, y, z, yaw, pitch):
    return "camera minecraft:overworld %s %s %s %s %s\n" % (x, y, z, yaw, pitch)


def views(prefix, d, y, pitch=4, tag=""):
    """front / three-quarter / side / back around a mob standing at the origin facing +z (south)."""
    return (cam(0, y, d, 180, pitch) + "wait 20\nshot %s_front\n" % prefix
            + cam(d * 0.7, y, d * 0.7, 135, pitch) + "wait 12\nshot %s_three_quarter\n" % prefix
            + cam(d, y, 0, 90, pitch) + "wait 12\nshot %s_side\n" % prefix
            + cam(0, y, -d, 0, pitch) + "wait 12\nshot %s_back\n" % prefix)


def pose(prefix, selector, action, ticks, d, y, pitch=4, yaw=90, cx=None, cz=0, cmp=True):
    """Trigger an action and shoot at the given ticks from the side (camera on +x looking west by default);
    with cmp, the same ticks again with the cube model (shots named cubes_...)."""
    cx = d if cx is None else cx
    runs = [("on", prefix)]
    if cmp:
        runs.append(("off", "cubes_" + (prefix[3:] if prefix.startswith("lp_") else prefix)))
    s = ""
    for mode, pre in runs:
        s += "lowpoly %s\n" % mode + cam(cx, y, cz, yaw, pitch) + "wait 30\n"
        s += "cmd skyabyss dev anim %s %s\n" % (selector, action)
        last = 0
        for t in ticks:
            s += "wait %d\nshot %s_%s_%02d\n" % (t - last, pre, action, t)
            last = t
        s += "wait 50\n"
    return s + "lowpoly on\n"


def write(name, body, title):
    path = os.path.join("tools", "shots", "lp_%s.txt" % name)
    with open(path, "w", encoding="utf-8") as f:
        f.write(HEAD.format(title=title) + body + "quit\n")
    print("wrote", path)


def main():
    # captain: 2.75 tall, with the pike on socket_main
    b = "cmd summon skyabyss:whalebone_captain 0 -60 0 {NoAI:1b,Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}\n"
    b += cam(0, -60, 6, 180, 4) + "waitchunks\nwait 60\n"
    b += views("lp_captain_idle", 4.8, -60)
    b += cam(0.3, -59.0, 2.2, 180, 0) + "wait 12\nshot lp_captain_face\n"
    b += cam(2.2, -59.4, 2.6, 150, 6) + "wait 12\nshot lp_captain_pike\n"
    b += pose("lp_captain", "@e[tag=m]", "sweep", (4, 8, 12, 16), 4.8, -60)
    b += pose("lp_captain", "@e[tag=m]", "slam", (4, 8, 12, 16, 20), 5.5, -60)
    b += pose("lp_captain", "@e[tag=m]", "roar", (6, 14), 4.8, -60)
    b += "lowpoly off\nwait 5\n" + cam(0, -60, 4.8, 180, 4) + "wait 20\nshot cubes_captain_front\n" + "lowpoly on\n"
    write("captain", b, "whalebone_captain low-poly: idle views, face, pike, sweep/slam/roar")

    # moss crawler (scale 1.3)
    b = "cmd summon skyabyss:moss_crawler 0 -60 0 {NoAI:1b,Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}\n"
    b += cam(0, -61, 5, 180, 4) + "waitchunks\nwait 60\nfov 40\n"
    b += views("lp_crawler_idle", 5, -61)
    b += cam(0, -57.1, 0.2, 180, 90) + "wait 12\nshot lp_crawler_top\n"
    b += cam(0.6, -61.5, 3.4, 180, 3) + "wait 12\nshot lp_crawler_face\n"
    b += pose("lp_crawler", "@e[tag=m]", "pounce", (3, 6, 9, 12, 16), 3.6, -61)
    b += pose("lp_crawler", "@e[tag=m]", "hurt", (4,), 3.6, -61)
    b += pose("lp_crawler", "@e[tag=m]", "death", (10, 25, 45), 3.6, -61)
    b += "lowpoly off\nwait 5\n" + cam(0, -61, 5, 180, 4) + "wait 20\nshot cubes_crawler_front\nlowpoly on\n"
    write("crawler", b, "moss_crawler low-poly: idle views, top, face, pounce, hurt, death")

    # rib archer (bow with strings on socket_off)
    b = "cmd summon skyabyss:rib_archer 0 -60 0 {NoAI:1b,Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}\n"
    b += cam(0, -60, 4.5, 180, 4) + "waitchunks\nwait 60\n"
    b += views("lp_archer_idle", 3.4, -60)
    b += cam(0.3, -59.0, 1.8, 180, 0) + "wait 12\nshot lp_archer_face\n"
    b += cam(-1.6, -59.4, 2.0, 215, 6) + "wait 12\nshot lp_archer_bow\n"
    b += pose("lp_archer", "@e[tag=m]", "shoot", (3, 6, 9, 12, 15, 18, 22), 3.2, -60)
    b += "lowpoly off\nwait 5\n" + cam(0, -60, 4.5, 180, 4) + "wait 20\nshot cubes_archer_front\nlowpoly on\n"
    write("archer", b, "rib_archer low-poly: idle views, face, bow, shoot (draw/release, strings)")

    # waterway maw (scale 0.58)
    b = "cmd summon skyabyss:waterway_maw 0 -59 0 {NoAI:1b,NoGravity:1b,Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}\n"
    b += cam(0, -60, 5, 180, 2) + "waitchunks\nwait 60\n"
    b += views("lp_maw_idle", 5, -60, 2)
    b += cam(0, -57, 0.5, 180, 90) + "wait 12\nshot lp_maw_top\n"
    b += pose("lp_maw", "@e[tag=m]", "bite", (3, 6, 9, 12, 16, 20), 3.6, -60, 2)
    b += "lowpoly off\nwait 5\n" + cam(0, -60, 5, 180, 2) + "wait 20\nshot cubes_maw_front\nlowpoly on\n"
    write("maw", b, "waterway_maw low-poly: idle views, top, bite")

    # stone whale heart: phases 1-3, intro and death
    b = ""
    for ph, hp in ((1, 450), (2, 248), (3, 90)):
        b += "cmd kill @e[type=!minecraft:player,distance=..80]\n"
        b += "cmd summon skyabyss:stone_whale_heart 0 -57 0 {NoAI:1b,Health:%df,Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}\n" % hp
        b += cam(0, -56, 9, 180, 0) + "waitchunks\nwait 80\n"
        b += "shot lp_heart_p%d_front\n" % ph
        b += cam(5, -55, 6, 150, 10) + "wait 15\nshot lp_heart_p%d_three_quarter\n" % ph
        b += cam(9, -56, 0, 90, 0) + "wait 15\nshot lp_heart_p%d_side\n" % ph
        b += cam(0, -56, -9, 0, 0) + "wait 15\nshot lp_heart_p%d_back\n" % ph
        b += cam(0, -50, 0.5, 180, 85) + "wait 15\nshot lp_heart_p%d_top\n" % ph
        for act in (("roar_1", (6, 14)), ("thrust", (4, 8, 12)), ("reclose", (6, 14))) if ph == 1 else \
                (("roar_2", (6, 14)), ("thrust", (6,)), ("reclose", (8,))) if ph == 2 else (("roar_2", (8,)), ("sweep", (6,)), ("reclose", (8,))):
            b += pose("lp_heart_p%d" % ph, "@e[tag=m]", act[0], act[1], 9, -56, 0)
    b += "cmd kill @e[type=!minecraft:player,distance=..80]\n" + cam(0, -57, 11, 180, -6) + "wait 10\n"
    b += "cmd summon skyabyss:stone_whale_heart 0 -59 0 {Rotation:[0f,0f],PersistenceRequired:1b}\n"
    for t in (8, 24, 40, 56, 72):
        b += "wait %d\nshot lp_heart_intro_%02d\n" % (8 if t == 8 else 16, t)
    b += "wait 20\ncmd kill @e[type=skyabyss:stone_whale_heart]\n"
    last = 0
    for t in (6, 24, 44, 64, 84, 98):
        b += "wait %d\nshot lp_heart_death_%02d\n" % (t - last, t)
        last = t
    b += "cmd kill @e[type=!minecraft:player,distance=..80]\n"
    write("heart", b, "stone_whale_heart low-poly: phases 1-3 views and attack poses, intro, death")


if __name__ == "__main__":
    main()
