def M(name, accent, glow):
    return Model(name, accent=accent, glowmat=glow)


def diamond(m, name, mat, c, s, d, t0, t1, zc=0.0):
    h = s / (2 * math.sqrt(2))
    m.seg(name, mat, (c[0] - h, c[1] - h), (c[0] + h, c[1] + h), s, d, t0, t1, over=0, zc=zc)


# ================================================================ 番兵長の鉾

def captain_pike():
    """番兵長の鉾: 煤けた鉄の長柄に骨の継ぎ輪。穂は骨の幅広の木の葉形で、中筋に髄の光。
    穂の根元から左右へ肋骨のような骨の翼が上へ反り、柄の途中に番兵長の房（鉄の輪に垂れる骨の札）"""
    I, Bn, Mw = 'soot', 'pbone', 'marrow'
    m = M('captain_pike', Bn, Mw)
    m.box('grip', I, [-1.5, -16, -1.5], [1.5, 0, 1.5], grad=(-16, 2, 0, 4), wrap=(-16, 0))
    m.box('butt', Bn, [-1.9, -18.5, -1.9], [1.9, -16, 1.9], grad=(-18.5, 2, -16, 4))
    m.seg('butt_tip', Bn, (0, -18.5), (0, -21), 2.25, 1.1, 3, 5, tip=True)
    m.box('haft', I, [-1.25, 0, -1.25], [1.25, 34, 1.25], grad=(0, 3, 34, 6))
    for k, y in enumerate((0, 12, 24)):                                      # 骨の継ぎ輪（上ほど細い）
        r = 1.9 - k * 0.1
        m.box(f'ring_{k}', Bn, [-r, y - 0.75, -r], [r, y + 0.75, r], 4)
    m.box('tassel_ring', I, [-1.8, 18, -1.8], [1.8, 19.25, 1.8], 5)          # 房の輪と、横へ垂れる骨の札
    m.chain('tassel', Bn, [(1.5, 18.5), (3, 17), (3.5, 14)], [1, 1], 0.4, 3, 4, tip=False)
    m.box('tag', Bn, [2.5, 11, -0.5], [4.5, 14, 0.5], grad=(11, 3, 14, 5))
    m.box('socket', I, [-2, 33, -2], [2, 37, 2], grad=(33, 3, 37, 6))
    m.box('socket_lip', Bn, [-2.4, 36.5, -2.4], [2.4, 37.75, 2.4], 4)
    for sd, n in ((-1, 'l'), (1, 'r')):                                      # 肋の翼（上へ反って先が尖る）
        m.chain(f'wing_{n}', Bn, [(sd * 1.5, 37.5), (sd * 4.5, 38.5), (sd * 6.5, 41), (sd * 7, 44.5)], [2.5, 2, 1.5], 0.9, 3, 5, tip=True)
    # 穂: 根元で広がり先で細る木の葉形（左右の半分を段で）
    for k, (y, w) in enumerate(((37.5, 2.5), (40, 3.5), (43, 4), (46.5, 3.75), (50, 3), (53, 2), (55.5, 1))):
        y1 = (40, 43, 46.5, 50, 53, 55.5, 57.5)[k]
        m.box(f'leaf_{k}', Bn, [-w, y, -1], [w, y1, 1], grad=(y, 3 + k * 0.2, y1, 4 + k * 0.2))
    m.box('leaf_tip', Bn, [-0.5, 57.5, -0.75], [0.5, 59.5, 0.75], 5)
    m.box('rib_glow', Mw, [-0.5, 39, -1.1], [0.5, 54, 1.1], grad=(39, 2, 54, 4))   # 中筋の髄
    return m


# ================================================================ 鍛冶の大鎚

def smith_hammer():
    """鍛冶の大鎚: 革を巻いた太く短い柄の先に、煤の鉄の大きな角頭。+x は平たい打つ面で、赤く焼けて光る。
    -x は楔の形のペン。頭の上下に鍛え目の帯、柄との間に鉄の楔"""
    I, H, R = 'forge', 'hide', 'heat'
    m = M('smith_hammer', H, R)
    m.box('grip', H, [-1.75, -7, -1.75], [1.75, 7, 1.75], grad=(-7, 2, 7, 4), wrap=(-7, 7))
    m.box('pommel', I, [-2.25, -9.5, -2.25], [2.25, -7, 2.25], grad=(-9.5, 2, -7, 4))
    m.box('haft', I, [-1.5, 7, -1.5], [1.5, 19, 1.5], grad=(7, 3, 19, 5))
    m.box('haft_strap', H, [-1.9, 12, -1.9], [1.9, 13.5, 1.9], 3)             # 柄の上の革の締め
    m.box('collar', I, [-2.25, 18, -2.25], [2.25, 20, 2.25], 5)
    m.box('head', I, [-6, 19.5, -3.5], [6, 27.5, 3.5], grad=(19.5, 3, 27.5, 6))
    m.box('band_d', I, [-6.4, 19.25, -3.9], [6.4, 20.75, 3.9], 6)             # 鍛え目の帯（上下）
    m.box('band_u', I, [-6.4, 26.25, -3.9], [6.4, 27.75, 3.9], 7)
    m.box('wedge', I, [-0.6, 27.5, -1.25], [0.6, 28.75, 1.25], 4)             # 頭の上に出た楔
    m.box('face', I, [6, 20, -3.25], [7.5, 27, 3.25], grad=(20, 5, 27, 7))    # +x の打つ面（張り出し）
    m.box('face_glow', R, [7.5, 20.75, -2.5], [8, 26.25, 2.5], grad=(20.75, 2, 26.25, 4))
    m.seg('peen', I, (-6, 23.5), (-10.5, 23.5), 6, 2.5, 4, 6, tip=True)       # -x の楔のペン
    m.box('heat_seam', R, [5.25, 21, -3.6], [6, 26, 3.6], grad=(21, 1, 26, 3))  # 焼けが頭の縁へ回る
    return m


# ================================================================ 下僕の火かき棒

def thrall_poker():
    """下僕の火かき棒: 輪の柄頭と、ねじった細い鉄の棒。先は +x へ曲がる鉤と、まっすぐの突き先。
    先から三分の一ほどが赤く焼けていて、熱が棒を下りるほど暗くなる"""
    I, H, R = 'forge', 'hide', 'heat'
    m = M('thrall_poker', H, R)
    m.box('grip', H, [-1.4, -10, -1.4], [1.4, 2, 1.4], grad=(-10, 2, 2, 4), wrap=(-10, 2))
    m.box('grip_cap', I, [-1.8, -10.75, -1.8], [1.8, -9.5, 1.8], 4)
    m.arc('loop', I, (0, -14.25), 3.25, 90, 450, 8, 1.25, 0.8, 4, 6)          # 輪の柄頭
    m.box('ferrule', I, [-1.8, 1.5, -1.8], [1.8, 3, 1.8], 5)
    for k in range(8):                                                       # ねじり: 菱形と四角を交互に
        y = 3 + k * 3
        if k % 2:
            diamond(m, f'twist_{k}', I, (0, y + 1.5), 2.6, 0.95, 3 + k * 0.2, 3.5 + k * 0.2)
        else:
            m.box(f'twist_{k}', I, [-0.95, y, -0.95], [0.95, y + 3, 0.95], grad=(y, 3 + k * 0.2, y + 3, 3.5 + k * 0.2))
    m.box('neck', I, [-0.8, 27, -0.8], [0.8, 31, 0.8], grad=(27, 4, 31, 6))
    m.box('heat_neck', R, [-0.85, 31, -0.85], [0.85, 36, 0.85], grad=(31, 0, 36, 2))
    m.seg('spike', R, (0, 36), (0, 41), 1.75, 0.8, 2, 4, tip=True)            # まっすぐの突き先
    m.chain('hook', R, [(0.4, 34), (3, 35), (4.5, 33.5), (4.25, 31)], [1.5, 1.25, 1], 0.75, 2, 4, tip=True)
    return m


# ================================================================ 番人の薙刀

def warden_glaive():
    """番人の薙刀: 嵐の鉄紺の長柄に銅の輪。先の受け口から +x へ反る幅のある片刃（背は -x でまっすぐ、刃は弧）。
    刃の縁に稲妻の黄、背に小さな雷の鉤。柄頭は銅の石突き"""
    G_, Cu, Sp = 'gale', 'brass', 'spark'
    m = M('warden_glaive', Cu, Sp)
    m.box('grip', G_, [-1.5, -16, -1.5], [1.5, 0, 1.5], grad=(-16, 2, 0, 4), wrap=(-16, 0))
    m.box('butt', Cu, [-1.9, -19, -1.9], [1.9, -16, 1.9], grad=(-19, 2, -16, 4))
    diamond(m, 'butt_tip', Cu, (0, -20.25), 2.5, 1.1, 3, 5)
    m.box('haft', G_, [-1.25, 0, -1.25], [1.25, 31, 1.25], grad=(0, 3, 31, 6))
    for k, y in enumerate((0.5, 10, 20)):
        m.box(f'ring_{k}', Cu, [-1.8, y - 0.6, -1.8], [1.8, y + 0.6, 1.8], 4)
    m.box('socket', Cu, [-2, 30, -2], [2, 34, 2], grad=(30, 3, 34, 5))
    m.box('socket_lip', G_, [-2.3, 33.5, -2.3], [2.3, 34.75, 2.3], 6)
    # 刃: 背（-x 側）は柄の線のまま上へ、刃（+x）は弧で膨らみ、先で背へ戻る
    for k, (y, w) in enumerate(((34.5, 2.5), (37.5, 4.25), (41, 5.25), (44.5, 5.5), (48, 5), (51, 4), (53.5, 2.75))):
        y1 = (37.5, 41, 44.5, 48, 51, 53.5, 55.5)[k]
        m.box(f'blade_{k}', G_, [-1.5, y, -0.9], [-1.5 + w, y1, 0.9], grad=(y, 4 + k * 0.25, y1, 5 + k * 0.25))
    m.seg('blade_tip', G_, (-0.5, 55), (-1.5, 59), 2.25, 0.8, 6, 7, tip=True)
    edge = [(1, 35.5), (2.75, 38.5), (3.75, 42), (4, 45.5), (3.5, 49), (2.5, 52), (1.25, 54.5)]
    m.chain('edge_glow', Sp, edge, [1, 1, 1, 1, 1, 1], 0.95, 2, 4, tip=False)
    m.chain('back_hook', Cu, [(-1.5, 46), (-3.5, 47.5), (-4, 50)], [1.5, 1.25], 0.7, 4, 5, tip=True)   # 背の雷の鉤
    m.box('spine', Cu, [-1.9, 35, -1], [-1.3, 54, 1], grad=(35, 3, 54, 5))    # 背の銅の筋
    return m


# ================================================================ 旅の盾

def travel_shield():
    """旅の盾: 縦に並べた樫の板（板ごとに色を少し変える）を丸く切り、黒鉄の縁と十字の帯で留める。
    中央に鉄の丸い突起（ボス）と鋲。裏に革の握りと当て木。前は -Z"""
    W, F = 'oak', 'iron'
    m = M('travel_shield', F, F)
    cy = 10
    # 板: x 方向に 5 枚。各板の上下は円の内側
    planks = [(-11, -6.6, 4), (-6.6, -2.2, 5), (-2.2, 2.2, 4.5), (2.2, 6.6, 5.5), (6.6, 11, 4)]

    for k, (x0, x1, t) in enumerate(planks):
        xm = max(abs(x0), abs(x1)) - 0.5
        dy = math.sqrt(max(0.0, 12 ** 2 - xm ** 2))
        m.box(f'plank_{k}', W, [x0 + 0.1, cy - dy, -2], [x1 - 0.1, cy + dy, 0], grad=(cy - dy, t - 1.5, cy + dy, t + 0.5))
    # 縁: 円を 12 節の弧で
    m.arc('rim', F, (0, cy), 12.25, 0, 360, 12, 2, 1.4, 4, 6, zc=-1)
    # 十字の帯と鋲
    m.box('band_h', F, [-11.5, cy - 1, -2.5], [11.5, cy + 1, -1.75], 5)
    m.box('band_v', F, [-1, cy - 11.5, -2.5], [1, cy + 11.5, -1.75], 5)
    for k, (x, y) in enumerate(((-8, cy), (8, cy), (0, cy - 8), (0, cy + 8))):
        m.box(f'rivet_{k}', F, [x - 0.6, y - 0.6, -2.9], [x + 0.6, y + 0.6, -2.4], 8)
    m.box('boss', F, [-2.75, cy - 2.75, -3.75], [2.75, cy + 2.75, -2.25], grad=(cy - 2.75, 4, cy + 2.75, 7))
    m.box('boss_top', F, [-1.5, cy - 1.5, -4.5], [1.5, cy + 1.5, -3.75], 8)
    # 裏
    m.box('handle', 'hide', [-1.5, cy - 4.5, 0], [1.5, cy + 4.5, 2.5], grad=(cy - 4.5, 2, cy + 4.5, 4))
    m.box('brace_0', W, [-9, cy - 7, 0], [9, cy - 5.5, 1], 3)
    m.box('brace_1', W, [-9, cy + 5.5, 0], [9, cy + 7, 1], 3)
    return m


