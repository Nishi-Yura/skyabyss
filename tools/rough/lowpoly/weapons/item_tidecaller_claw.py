"""潮招きの爪 (作り直し)。蟹の鋏: 要の真珠で留めた 2 枚の鋏の刃 (右が長く固定、左が短く動く) が内へ曲がって噛み合い、内側に鋸の歯。
握りは真下 (y 2.5、変えない)。y -1..19。
階級: 通常 = 素の鋏 + 帯 / レア = 背の貝の板 + 珊瑚の襟 + 帯 2 本 + 藤壺 / 伝説 = 外の小さな鋏の爪 + 刃のあいだの珊瑚の冠 + 長い帯と海藻。"""
