CX = cx_interp([6.4, 10, 14, 17.4, 19.2], [1.4, 3.8, 4.4, 3.0, 1.2])


def tooth(x, y, s, L=1.8):
    return spike(BONE, "edge", (x, y, 0), (-s * 1.0, 0.45, 0), L, 0.55, sides=3, rings=1, hint=(0, 0, 1))


def faces(r="common"):
    t = {"common": 0, "rare": 1, "legend": 2}[r]
    f = []
    # 握り: 海藻の巻き、石突きの巻貝、鍔
    f += prism("wrap", (0, -0.4, 0), (0, 4.6, 0), 1.2, 1.1, sides=6, caps=(False, False))
    f += spike(BONE, "main", (0, -0.4, 0), (0, -1, 0), 1.6, 1.2, sides=6, rings=1, hint=(1, 0, 0))
    f += block("guard", (0, 5.0, 0), (4.2, 1.6, 3.2), taper=(0.9, 0.9))
    f += barnacles((0.4, 2.0, -1.2), 3, 0.45, 0.4, 0.7)
    # 要: 真珠層の円盤を貫く真珠
    f += prism("main", (0, 7.0, -1.4), (0, 7.0, 1.4), 2.3, 2.3, sides=6, caps=(True, True), phase=0, hint=(1, 0, 0))
    f += pearl((0, 7.0, -1.9), 1.0)
    # 右の刃 (固定、長く、内へ曲がる)
    f += blade("spine", [(6.4, -1.3, 1.3, 1.0, 1.0, 1.4), (10.0, -1.5, 1.5, 1.1, 1.1, 3.8), (14.0, -1.2, 1.2, 0.9, 0.9, 4.4),
                         (17.4, -0.7, 0.7, 0.5, 0.5, 3.0), (19.2, 0, 0, 0, 0, 1.2)],
               colmats=["edge", "spine", "edge", "edge", "spine", "edge"])
    # 左の刃 (動く、短く、内へ曲がる)
    f += blade("main", [(6.4, -1.3, 1.3, 1.0, 1.0, -1.4), (9.6, -1.4, 1.4, 1.1, 1.1, -3.4), (13.2, -1.1, 1.1, 0.9, 0.9, -3.6),
                        (16.2, 0, 0, 0, 0, -2.2)])
    # 内側の鋸の歯
    for y in (10.6, 13.2, 15.6):
        f += tooth(3.0 + (0.9 if y > 13 else 0), y, 1)
    for y in (10.2, 12.6):
        f += tooth(-2.4, y, -1, 1.6)
    # 帯
    f += sash([(1.4, 5.8, -1.4), (2.6, 3.2, -1.8), (1.6, -0.2, -1.2)], 1.6, th=0.2, taper=0.45)
    if t >= 1:
        f += sash([(-1.4, 5.8, 1.2), (-2.8, 3.0, 1.6), (-2.0, -0.6, 1.0)], 1.4, th=0.2, taper=0.45)
        # 背の貝の板 (固定刃の背に)
        f += block("main", (5.2, 12.4, 0.0), (1.1, 5.4, 2.0), rot=rot_z(-8), taper=(0.7, 0.9))
        f += block("trim", (0, 5.9, 0), (4.8, 0.7, 3.4))
        f += block("trim", (0, -0.2, 0), (2.8, 0.7, 2.8))
        for s in (1, -1):
            f += spike(BONE, "acc", (s * 1.0, 8.6, 0.6), (s * 0.25, 1, 0.3), 3.2, 0.8, sides=4, rings=1, hint=(1, 0, 0))
    if t == 2:
        # 刃のあいだの珊瑚の冠と、外の小さな鋏の爪
        f += spike(BONE, "acc", (0, 8.8, 0.2), (0, 1, 0), 6.2, 0.9, sides=4, rings=2, hint=(1, 0, 0))
        f += blade("main", [(7.4, -0.9, 0.9, 0.8, 0.8, 4.2), (10.4, -0.9, 0.9, 0.8, 0.8, 6.6), (13.6, 0, 0, 0, 0, 6.8)])
        f += pearl((-3.0, 8.2, -1.2), 0.7)
        f += sash([(0.6, 5.8, 1.6), (0.4, 1.8, 2.4), (1.2, -2.2, 1.6)], 1.5, th=0.22, taper=0.45)
    return f


