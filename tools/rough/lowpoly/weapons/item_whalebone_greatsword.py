    f += block("gem", (2.6, 19.8, 0), (1.3, 1.4, 1.5), taper=(0.6, 0.6), rot=rot_z(-20))   # 折れ口の核
    if t == 0:
        f += block("edge", (-3.8, 4.2, 0), (4.2, 1.4, 2.4), rot=rot_z(10), taper=(0.6, 0.8))   # 短い鍔
        f += block("edge", (3.8, 4.2, 0), (3.4, 1.4, 2.4), rot=rot_z(-10), taper=(0.6, 0.8))
        f += tooth(-3.0, 9.4, (-1, -0.4, 0), 2.6, 0.8)
    else:
        f += curve("edge", [(-2.0, 4.2, 0), (-5.2, 4.0, 0), (-7.4, 2.6, 0), (-7.8, 0.2, 0)], [1.4, 1.2, 0.9, 0.0], [1.5, 1.3, 1.0, 0.0], sides=4)
