"""B案「嵐の隼」: 前のめりに首を突き出した猛禽の姿。ほぼ黒に近い藍の鎧、細く長い隼の兜 (嘴だけ銅)、
後ろへ流れる冠羽、胴の龍骨 (胸の稜)、尾羽、折りたたんだ翼の形の長い風切りのマント、長い逆関節と大きな爪。
鉤槍は細長い銛状で、軸から長い羽の吹き流しが後ろへ流れる。藍黒 + 白金の羽の縁 + 銅と金の差し色。"""
from common import *  # noqa

INDIGO = [(8, 10, 22), (20, 24, 46), (38, 46, 78), (62, 74, 110), (96, 110, 150), (146, 160, 196)]
PLAT = [(30, 36, 58), (74, 84, 118), (130, 142, 176), (186, 198, 222), (226, 234, 248), (250, 252, 255)]
COP = [(36, 18, 12), (84, 42, 20), (136, 72, 32), (184, 104, 46), (226, 146, 72), (252, 196, 120)]
VERD = [(36, 70, 66), (62, 110, 98), (92, 148, 128)]
ASH = [(26, 24, 30), (48, 46, 54), (76, 72, 80), (110, 106, 112)]
PAL = {"mats": {
    "steel": dict(ramp=INDIGO, kind="plate", base=0.6, per=8, noise=0.03),
    "feather": dict(ramp=PLAT, kind="feather", base=0.66, fvar=1, noise=0.03),
    "dkfeather": dict(ramp=INDIGO, kind="feather", base=0.68, fvar=1, noise=0.03, bw=0.4),
    "copper": dict(ramp=COP, base=0.72, noise=0.08, stain=dict(ramp=VERD, thr=0.97, up=0.2, conc=0.25)),
    "wood": dict(ramp=ASH, base=0.7, stripe=7),
    "glow": dict(ramp=[(150, 214, 255), (210, 240, 255), (250, 252, 255)], base=0.8, glow=True),
}}
HEAD_CENTER, HEAD_SCALE = (0, 31.0, -3.5), 17.0


def build():
    F = []
    # ------------------------------------------------------------ 頭: 隼の面頬
    R = [ring(26.0, 1.8, -2.2, 2.0, -2.8), ring(28.4, 3.0, -4.2, 2.6, -2.8), ring(30.2, 3.5, -5.4, 3.0, -3.0),
         ring(32.0, 3.3, -4.8, 4.6, -2.6), ring(33.6, 2.3, -2.6, 6.0, -1.8)]
    F += loft2("head", R, lambda i, j: "void" if (i == 1 and j in (7, 0)) else "steel", caps=("steel", "steel"))
    eyes = [dict(c=(2.0, 29.4, -5.6), rx=1.2, ry=0.45, zr=2.0), dict(c=(-2.0, 29.4, -5.6), rx=1.2, ry=0.45, zr=2.0)]
    F += tube("head", "copper", [(0, 30.8, -7.0), (0, 30.0, -11.0), (0, 27.4, -12.2)], ra=[1.5, 1.0, 0.12], rb=[1.5, 1.0, 0.12],
              sides=4, hint=(1, 0, 0))
    # 冠羽 (後ろへ流れる)
    for x, y, ln in ((0, 34.0, 11.5), (-1.4, 33.4, 9.5), (1.4, 33.4, 9.5)):
        F += feather("head", "dkfeather", (x, y, -0.2), (x * 1.6, y + 1.6, -0.2 + ln), 2.2, ref=(x, y + 6, 1.5 + ln / 2), fold=0.4, n_mid=0.4)
    for s in (-1, 1):
        for k in range(2):
            F += feather("head", "feather", (s * 3.2, 30.0 - 1.0 * k, -2.0), (s * 5.0, 28.6 - 1.4 * k, 5.0), 2.0,
                         ref=(s * 9, 30, 2.0), fold=0.3)
    # ------------------------------------------------------------ 胴 (前傾・龍骨)
    T = [ring(13.2, 3.0, -2.0, 2.4, 0.8), ring(16.0, 3.6, -3.4, 2.4, -0.2), ring(19.5, 4.2, -4.8, 2.4, -1.4),
         ring(22.8, 4.4, -3.8, 2.6, -2.6), ring(25.0, 2.6, -2.4, 2.0, -3.4)]
    F += loft2("body", T, lambda i, j: "steel", caps=("steel", "steel"))
    for y, ks, w, h, fl in ((23.4, (-1.35, -0.45, 0.45, 1.35), 3.6, 5.2, 1.1), (19.4, (-1.3, -0.45, 0.45, 1.3), 3.4, 5.4, 1.2),
                            (15.8, (-0.9, 0.0, 0.9), 3.2, 4.8, 1.2)):
        for k in ks:
            p, n = surf(T, y, k % 8)
            F += shingle("body", "feather", p, (0, -1, 0.1), n, w, h, fl)
    # 尾羽
    for i, x in enumerate((-3.2, -1.6, 0.0, 1.6, 3.2)):
        F += feather("body", "dkfeather" if i % 2 == 0 else "feather", (x * 0.6, 14.4, 2.2), (x * 1.5, 4.5 + 0.8 * abs(x), 12.5 - 0.5 * abs(x)),
                     3.0, ref=(x * 0.6, 20, 6), fold=0.45, n_mid=0.4)
    # 腰の草摺
    for k in (-2.0, -1.0, 0.0, 1.0, 2.0):
        p, n = surf(T, 13.8, k % 8)
        F += shingle("body", "dkfeather", p, (0, -1, 0), n, 3.0, 5.0, 1.1)
    # ------------------------------------------------------------ 腕 (翼腕: 籠手と後ろへ流れる羽)
    for s, a, f, elbow, wrist in ((-1, "arm_l", "forearm_l", V(-6.6, 17.5, -0.5), V(-6.6, 12.4, -3.0)),
                                  (1, "arm_r", "forearm_r", V(6.6, 17.5, -1.5), V(6.6, 12.4, -4.3))):
        F += tube(a, "steel", [(s * 5.0, 23.8, -2.6), (s * 5.9, 20.4, -1.8), (s * 6.4, 17.8, -1.2)], ra=[1.6, 1.3, 1.2],
                  rb=[1.6, 1.3, 1.2], sides=5, hint=(1, 0, 0))
        for k in range(3):
            F += feather(a, "feather" if k != 1 else "dkfeather", (s * 4.6, 24.0 - 0.5 * k, -2.4 + 1.1 * k), (s * (7.4 + 0.5 * k), 17.5 - 1.4 * k, 6.0 + 1.5 * k),
                         3.0, ref=(s * 9, 22, 2.0), fold=0.4, n_mid=0.4)
        F += tube(f, "steel", [elbow, (elbow + wrist) / 2, wrist], ra=[1.3, 1.5, 1.1], rb=[1.3, 1.5, 1.1], sides=5, hint=(1, 0, 0))
        for k in range(3):
            F += feather(f, "feather", elbow + V(s * 1.3, -0.6 * k, 0.4 + 0.5 * k), elbow + V(s * (2.4 + 0.4 * k), -3.4 - 1.2 * k, 9.5 - 0.6 * k),
                         2.0, ref=(s * 9, 14, 3), fold=0.3, n_mid=0.4)
        F += ellipsoid(f, "steel", wrist + V(0, -0.6, -0.4), (1.3, 1.2, 1.4), segs=5, rings=1)
        if s == -1:
            for dx in (-0.9, 0.0, 0.9):
                F += spike(f, "copper", wrist + V(dx, -1.2, -0.6), (dx * 0.5, -0.4, -1.0), 3.2, 0.5, sides=3, rings=1)
    # ------------------------------------------------------------ 折りたたんだ翼のマント
    for s, c in ((-1, "cloak_l"), (1, "cloak_r")):
        for i in range(6):
            F += feather(c, "dkfeather" if i % 2 == 0 else "feather", (s * (0.8 + 0.8 * i), 24.2 - 0.4 * i, 3.0 + 0.1 * i),
                         (s * (1.6 + 1.9 * i), -1.0 + 1.8 * i, 5.8 + 0.5 * i), 3.0, ref=(s * 4, 14, 10), fold=0.5, bow=0.6, n_mid=0.42)
        for i in range(3):
            F += feather(c, "feather", (s * (1.2 + 1.8 * i), 24.4, 2.8), (s * (2.4 + 2.2 * i), 12.0 + 1.0 * i, 3.4), 2.8,
                         ref=(s * 4, 14, 10), fold=0.4)
    # ------------------------------------------------------------ 脚 (長い逆関節と大きな爪)
    for s, b in ((-1, "leg_l"), (1, "leg_r")):
        x = s * 2.25
        F += tube(b, "steel", [(x, 13.4, 0.2), (x, 8.8, -2.6), (x, 4.6, 1.6)], ra=[1.5, 1.3, 1.0], rb=[1.5, 1.3, 1.0], sides=4, hint=(1, 0, 0))
        F += tube(b, "steel", [(x, 4.6, 1.6), (x, 2.0, 0.2)], ra=[1.0, 0.8], rb=[1.0, 0.8], sides=4, hint=(1, 0, 0))
        for dx in (-1.1, 0.0, 1.1):
            F += spike(b, "copper", (x + dx * 0.4, 1.4, -0.2), (dx * 0.4, -0.15, -1.0), 5.0, 0.6, sides=3, rings=1)
        F += spike(b, "copper", (x, 1.6, 0.6), (0, -0.1, 1.0), 2.8, 0.5, sides=3, rings=1)
    # ------------------------------------------------------------ 鉤槍: 細い銛
    G = []
    G += tube("glaive", "wood", [(0, -10, 0), (0, 4, 0), (0, 25, 0)], ra=[0.65, 0.7, 0.6], rb=[0.65, 0.7, 0.6], sides=4, hint=(1, 0, 0))
    G += spike("glaive", "copper", (0, -9.6, 0), (0, -1, 0), 2.4, 0.7, sides=3, rings=1)
    G += tube("glaive", "copper", [(0, 18.0, 0), (0, 19.6, 0)], ra=[1.0, 1.0], rb=[1.0, 1.0], sides=4, hint=(1, 0, 0))
    G += tube("glaive", "copper", [(0, 25, 0), (0, 32, 0), (0, 40.5, 0)], ra=[0.9, 0.7, 0.0], rb=[0.5, 0.4, 0.0], sides=4, hint=(1, 0, 0))
    # 二股の鉤 (隼の爪)
    for sd in (-1, 1):
        G += tube("glaive", "copper", [(0, 25, 0), (sd * 2.6, 27.2, 0), (sd * 5.4, 25.8, 0), (sd * 6.0, 22.8, 0)],
                  ra=[0.8, 0.75, 0.6, 0.5], rb=[0.7, 0.65, 0.5, 0.45], sides=4, hint=(0, 0, 1))
        G += tube("glaive", "glow", [(sd * 6.0, 22.8, 0), (sd * 6.1, 21.0, 0)], ra=[0.5, 0.0], rb=[0.45, 0.0], sides=4, hint=(0, 0, 1))
    # 吹き流し
    for k, (dz, ln) in enumerate(((0.9, 15.0), (-0.9, 12.0), (0.0, 9.0))):
        G += feather("glaive", "feather" if k != 1 else "dkfeather", (0, 20.5 - 1.2 * k, 0), (0.6 + dz * 0.5, 20.5 - 1.2 * k - ln * 0.35, 3.2 + ln * 0.9 + dz),
                     2.2, ref=(2, 16, 4), fold=0.3, n_mid=0.4)
    return F, G, eyes
