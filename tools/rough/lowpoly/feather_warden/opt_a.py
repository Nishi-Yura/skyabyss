"""A案「鷲兜の番人」: 直立した騎士の輪郭。鷲の嘴の兜 (銅) に避雷針の冠、重ね羽の肩当て、
背から垂れる 2 枚の風切りの羽のマント (cloak_l/r)、鳥の脚。鉤槍は鷲の爪の形の鉤と柄の羽飾り。
灰青の鋼 + 白青の羽 + 銅の縁取り。"""
from common import *  # noqa

STEEL = [(14, 20, 32), (30, 40, 58), (50, 64, 88), (76, 94, 122), (110, 130, 158), (156, 176, 202)]
FEA = [(30, 38, 54), (62, 76, 100), (108, 124, 150), (158, 174, 198), (204, 216, 234), (240, 246, 252)]
COP = [(36, 18, 12), (84, 42, 20), (136, 72, 32), (184, 104, 46), (226, 146, 72), (252, 196, 120)]
VERD = [(36, 70, 66), (62, 110, 98), (92, 148, 128)]
WOOD = [(24, 20, 22), (46, 40, 44), (72, 64, 68), (102, 92, 94)]
PAL = {"mats": {
    "steel": dict(ramp=STEEL, kind="plate", base=0.62, per=8, noise=0.03),
    "feather": dict(ramp=FEA, kind="feather", base=0.58, fvar=1, noise=0.03),
    "dkfeather": dict(ramp=STEEL, kind="feather", base=0.58, fvar=1, noise=0.03),
    "copper": dict(ramp=COP, base=0.72, noise=0.08, stain=dict(ramp=VERD, thr=0.97, up=0.2, conc=0.25)),
    "wood": dict(ramp=WOOD, base=0.7, stripe=7),
    "glow": dict(ramp=[(150, 214, 255), (210, 240, 255), (250, 252, 255)], base=0.8, glow=True),
}}
HEAD_CENTER, HEAD_SCALE = (0, 31.0, -2.0), 17.0


def build():
    F = []
    # ------------------------------------------------------------ 頭: 鷲の嘴の兜
    R = [ring(26.0, 2.2, -2.4, 2.6, n=6), ring(28.0, 3.2, -3.6, 3.4, n=6), ring(29.8, 4.0, -4.4, 4.0, n=6),
         ring(31.4, 4.0, -4.9, 4.2, n=6), ring(33.4, 3.2, -3.0, 3.8, n=6), ring(35.2, 1.8, -1.2, 3.0, n=6)]
    F += loft2("head", R, lambda i, j: "void" if (i == 2 and j in (5, 0)) else "copper", caps=("copper", "copper"))
    eyes = [dict(c=(2.0, 30.6, -3.7), rx=0.85, ry=0.45, zr=1.6), dict(c=(-2.0, 30.6, -3.7), rx=0.85, ry=0.45, zr=1.6)]
    # 嘴: 鷲のかぎ嘴
    F += tube("head", "copper", [(0, 32.6, -4.5), (0, 31.6, -8.0), (0, 28.4, -9.8)], ra=[2.0, 1.3, 0.15],
              rb=[1.8, 1.3, 0.15], sides=4, hint=(1, 0, 0))
    # 避雷針の冠
    for x, z, dz, ln in ((0, 0.8, 0.8, 6.2), (-2.0, 1.4, 0.9, 4.8), (2.0, 1.4, 0.9, 4.8), (0, 3.6, 1.6, 3.8)):
        d = nrm(V(x * 0.2, 1.0, dz))
        b0 = V(x, 35.0, z)
        F += tube("head", "copper", [b0, b0 + d * ln * 0.62], ra=[0.8, 0.5], rb=[0.8, 0.5], sides=3, hint=(1, 0, 0))
        F += tube("head", "glow", [b0 + d * ln * 0.62, b0 + d * (ln + 1.4)], ra=[0.5, 0.0], rb=[0.5, 0.0], sides=3, hint=(1, 0, 0))
    # 頬の風切り羽 (後ろへ流れる)
    for s in (-1, 1):
        for k, (dy, dz) in enumerate(((0.0, 7.5), (-2.0, 6.5))):
            F += feather("head", "dkfeather", (s * 3.9, 30.4 - 1.6 * k, 0.8), (s * 5.8, 29.4 + dy - 2.2 * k, 0.8 + dz),
                         2.2, ref=(s * 9, 30, 3.0), fold=0.35, bow=0.3)
    # ------------------------------------------------------------ 胴
    T = [ring(13.2, 3.2, -2.2, 2.2), ring(16.0, 3.8, -3.0, 2.6), ring(20.0, 4.4, -3.6, 3.0),
         ring(23.6, 4.6, -3.2, 2.8), ring(25.2, 2.6, -2.2, 2.0)]
    F += loft2("body", T, lambda i, j: "steel", caps=("steel", "steel"))
    # 胸の鎧羽 (3 段・下へ重なり)
    for y, angs, w, h, fl in ((23.4, (-52, -18, 18, 52), 3.8, 5.0, 1.0), (19.4, (-50, -17, 17, 50), 3.6, 5.2, 1.1),
                              (15.6, (-36, 0, 36), 3.4, 4.6, 1.1)):
        rx, rz = 4.4 + (y - 20) * 0.04, 3.4
        for a in angs:
            top = torso_pt(y, rx, rz, a)
            n = torso_n(a)
            F += shingle("body", "feather", top, (0, -1, 0), n + V(0, 0.2, 0) * 0, w, h, fl)
    # 腰の草摺
    for a in (-70, -42, -14, 14, 42, 70):
        top = torso_pt(13.6, 3.4, 2.6, a)
        F += shingle("body", "dkfeather", top, (0, -1, 0), torso_n(a), 3.2, 5.6, 1.2)
    # 背の銅板と避雷針の枝
    F += ellipsoid("body", "copper", (0, 19.0, 3.9), (2.8, 3.3, 1.3), segs=6, rings=1)
    for s in (-1, 1):
        F += tube("body", "copper", [(s * 2.0, 21.0, 4.4), (s * 3.0, 27.0, 5.6), (s * 3.7, 31.0, 5.2)], ra=[0.7, 0.6, 0.5],
                  sides=3, hint=(1, 0, 0))
        F += tube("body", "glow", [(s * 3.7, 31.0, 5.2), (s * 4.1, 33.4, 5.0)], ra=[0.5, 0.0], sides=3, hint=(1, 0, 0))
    # ------------------------------------------------------------ 肩の重ね羽
    for s, a in ((-1, "arm_l"), (1, "arm_r")):
        for k in range(3):
            F += feather(a, "feather" if k != 1 else "dkfeather", (s * 3.6, 25.4 - 0.3 * k, -0.3 + 0.3 * k),
                         (s * (9.6 - 0.2 * k), 20.6 - 1.9 * k, 0.3 * k), 5.4 - 0.6 * k, ref=(s * 6, 31, 0.3 * k),
                         fold=0.55, n_mid=0.5)
        F += tube(a, "steel", [(s * 5.2, 23.4, 0), (s * 6.0, 20.0, -0.4), (s * 6.4, 17.6, -0.9)], ra=[1.5, 1.3, 1.2],
                  rb=[1.5, 1.3, 1.2], sides=5, hint=(1, 0, 0))
    # 前腕: 籠手 + 羽の扇
    for s, f, wrist, elbow in ((-1, "forearm_l", V(-6.6, 12.4, -3.0), V(-6.6, 17.5, -0.5)),
                               (1, "forearm_r", V(6.6, 12.4, -4.3), V(6.6, 17.5, -1.5))):
        F += tube(f, "steel", [elbow, (elbow + wrist) / 2 + V(0, 0, 0.1), wrist], ra=[1.35, 1.5, 1.1], rb=[1.35, 1.5, 1.1],
                  sides=5, hint=(1, 0, 0))
        for k in range(3):
            F += feather(f, "feather", elbow + V(s * 1.4, -0.4 * k, 0.6 - 0.9 * k), wrist + V(s * (2.8 + k * 0.5), -2.4 - 0.8 * k, -1.2 - 0.9 * k),
                         2.4, ref=(s * 9, 14, -1.0), fold=0.35)
        F += ellipsoid(f, "steel", wrist + V(0, -0.6, -0.4), (1.3, 1.2, 1.4), segs=5, rings=1)
        if s == -1:
            for dx in (-0.8, 0.0, 0.8):
                F += spike(f, "copper", wrist + V(dx, -1.2, -0.6), (dx * 0.4, -0.5, -1.0), 2.8, 0.5, sides=3, rings=1)
    # ------------------------------------------------------------ 風切りのマント (cloak_l / cloak_r)
    for s, c in ((-1, "cloak_l"), (1, "cloak_r")):
        for i in range(5):
            F += feather(c, "feather" if i % 2 == 0 else "dkfeather", (s * (1.0 + 1.0 * i), 24.0 - 0.5 * i, 3.2),
                         (s * (2.0 + 2.0 * i), 2.5 + 1.6 * i, 4.4 + 0.2 * i), 3.4, ref=(s * 4, 14, 9), fold=0.5, bow=0.5, n_mid=0.4)
        for i in range(3):
            F += feather(c, "dkfeather", (s * (1.4 + 1.5 * i), 24.2, 3.0), (s * (2.2 + 2.0 * i), 12.0 + 1.0 * i, 3.6), 3.0,
                         ref=(s * 4, 14, 9), fold=0.4, n_mid=0.45)
    # ------------------------------------------------------------ 脚 (鳥の逆関節)
    for s, b in ((-1, "leg_l"), (1, "leg_r")):
        x = s * 2.25
        F += tube(b, "steel", [(x, 13.4, 0.2), (x, 8.2, -1.4), (x, 4.2, 0.6)], ra=[1.7, 1.5, 1.1], rb=[1.7, 1.5, 1.1],
                  sides=5, hint=(1, 0, 0))
        F += tube(b, "steel", [(x, 4.2, 0.6), (x, 1.8, 0.7)], ra=[1.1, 0.9], rb=[1.1, 0.9], sides=5, hint=(1, 0, 0))
        for dx in (-0.9, 0.0, 0.9):
            F += spike(b, "copper", (x + dx * 0.4, 1.2, 0.2), (dx * 0.35, -0.12, -1.0), 4.2, 0.55, sides=3, rings=1)
        F += spike(b, "copper", (x, 1.4, 1.2), (0, -0.1, 1.0), 2.2, 0.5, sides=3, rings=1)
    # ------------------------------------------------------------ 鉤槍 (geo 局所座標: 受け口の pivot が原点・柄は y)
    G = []
    G += tube("glaive", "wood", [(0, -10, 0), (0, 4, 0), (0, 24, 0)], ra=[0.8, 0.85, 0.7], rb=[0.8, 0.85, 0.7], sides=5, hint=(1, 0, 0))
    G += spike("glaive", "copper", (0, -9.6, 0), (0, -1, 0), 2.6, 0.8, sides=3, rings=1)
    for y in (-1.0, 9.0, 19.0):
        G += tube("glaive", "copper", [(0, y, 0), (0, y + 1.2, 0)], ra=[1.15, 1.15], rb=[1.15, 1.15], sides=5, hint=(1, 0, 0))
    # 穂先: 木の葉形の刃
    G += feather("glaive", "copper", (0, 24, 0), (0, 36.5, 0), 3.0, ref=(0, 30, -3), fold=0.5, taper=0.7, n_mid=0.35)
    G += feather("glaive", "copper", (0, 24, 0), (0, 36.5, 0), 3.0, ref=(0, 30, 3), fold=0.5, taper=0.7, n_mid=0.35)
    # 鉤: 鷲の爪の形 (横へ張り出して内へ曲がる)
    G += tube("glaive", "copper", [(0, 22.5, 0), (-3.5, 25.5, 0), (-8.0, 26.0, 0), (-10.5, 23.0, 0), (-9.5, 19.5, 0)],
              ra=[1.0, 1.0, 0.9, 0.7, 0.5], rb=[0.9, 0.9, 0.8, 0.6, 0.45], sides=4, hint=(0, 0, 1), phase=45)
    G += tube("glaive", "glow", [(-9.5, 19.5, 0), (-9.4, 17.6, 0)], ra=[0.5, 0.0], rb=[0.45, 0.0], sides=4, hint=(0, 0, 1))
    # 柄の羽飾り
    for k, dz in enumerate((-1.2, 1.2, 0.0)):
        G += feather("glaive", "feather", (0.9, 21.5, dz), (3.8 + k, 8.0 - 2.5 * k, dz * 2.2), 2.4, ref=(5, 16, dz * 3), fold=0.3)
    return F, G, eyes
