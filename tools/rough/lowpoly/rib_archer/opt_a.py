def hand(bone, s, wrist, belly=-1.0, fingers=3, sock=False):
    """手首の位置 wrist から出る細い指 (belly = 指が巻く向きの z)。"""
    F = []
    for i in range(fingers):
        dx = (i - (fingers - 1) / 2) * 0.65
        F += spike(bone, "bone", wrist + V(dx * 0.6, -0.2, 0.0), V(dx * 0.15, -0.5, belly), 3.0, 0.5, sides=3, rings=1,
                   bend=(0, -0.6, 0))
    return F


