def claws(bone, wrist, n=4, spread=0.6, ln=3.2, d=(0, -0.6, -0.8), belly=0.0):
    F = []
    for i in range(n):
        dx = (i - (n - 1) / 2) * spread
        F += spike(bone, "bone", wrist + V(dx, 0, 0), V(dx * 0.3 + d[0], d[1], d[2]), ln - abs(dx) * 0.3, 0.45, sides=3,
                   rings=1, bend=(0, -0.5, -0.6))
    return F


