def stag(bone, mat, base, d, length, r, branches=(), bend=(0, 0, 0), sides=4, rings=3, mats=None, hint=(1, 0, 0)):
    """枝珊瑚: 根元から d へ伸びる先細りの幹と、途中から出る枝 (t, 向きの足し, 長さ, 半径)。"""
    d = nrm(d)
    base = np.asarray(base, float)
    bend = np.asarray(bend, float)
    F = spike(bone, mat, base, d, length, r, sides=sides, rings=rings, bend=bend, hint=hint)
    for (t, add, ln, rr, *m) in branches:
        p = base + d * length * t + bend * t * t
        dd = nrm(nrm(d * length + 2 * bend * t) + np.asarray(add, float))
        F += spike(bone, (m[0] if m else mat), p, dd, ln, rr, sides=max(3, sides - 1), rings=1)
    return F


def hand_claw(bone, wrist, s, n=3, ln=3.0, belly=-0.5):
    F = []
    for i in range(n):
        dx = (i - (n - 1) / 2) * 0.7
        F += spike(bone, "bone", wrist + V(dx * 0.55, 0.0, 0.1 * abs(dx)), V(dx * 0.18, -1.0, belly), ln, 0.5, sides=3, rings=1,
                   bend=(0, 0, belly * 1.6))
    return F


