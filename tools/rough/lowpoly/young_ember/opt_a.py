def leg(bone, front):
    p = pv(bone)
    s = 1 if p[0] > 0 else -1
    F = []
    F += ellipsoid(bone, "rock", p + V(s * 4, 4, 0), (10, 10, 12), segs=8, rings=3)          # 肩・腿 (胴へ沈む)
    k = p + V(s * 3, -10, -2 if front else 1)
    f = V(p[0] + s * 3, 5, p[2] - 3)
    F += rod(bone, "rock", [p + V(s * 2, 0, 0), k, f], [9.0, 7.5, 6.5], sides=6, hint=(0, 0, 1))
    F += ellipsoid(bone, "skin", V(f[0], 3.5, f[2] - 2), (8.5, 3.6, 10.5), segs=8, rings=2)  # 足の甲
    F += claws(bone, V(f[0], 1.2, f[2] - 10.5), spread=4.2, length=4.5, r=1.5)
    return F


def bench(slat_mats=("bone", "bone2"), n=12):
    """骨の長椅子: 肋骨の板を前後に並べる (上面 = SEAT_Y、隙間なし)。"""
    F = []
    z0, z1 = -54.0, 54.0
    dz = (z1 - z0) / n
    for i in range(n):
        zc = z0 + dz * (i + 0.5)
        bot = rrect(V(0, 29, zc), (1, 0, 0), (0, 0, 1), 42, dz)
        top = rrect(V(0, SEAT_Y, zc), (1, 0, 0), (0, 0, 1), 56, dz)
        m = slat_mats[i % len(slat_mats)]
        F += loft("saddle", m, [bot, top], caps=(m, m))
    return F


