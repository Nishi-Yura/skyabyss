"""B 案: 鯨骨の亡者将軍 — 鎧より骨。鯨の頭骨の兜 (肋骨の冠)、胸は開いた肋の籠に光る核、背骨と尾椎、石は籠手と膝だけ。"""
from __future__ import annotations

