"""C 案: 岩鯨の石像守 — 岩を切り出した重い石像。胸びれの形の肩、尾びれの冠、背の一枚の大きな背びれ、苔むした暖かい灰色。"""
from __future__ import annotations

from ck import *

NAME = "岩鯨の石像守"
PAL = dict(
    STONE=ramp((46, 42, 40), (82, 76, 70), (118, 110, 100), (154, 144, 130), (190, 178, 160)),
    BONE=ramp((60, 50, 44), (116, 102, 82), (166, 150, 120), (206, 192, 158), (232, 220, 188), (248, 240, 216)),
    MOSS=ramp((16, 44, 40), (28, 74, 62), (46, 110, 88), (84, 154, 120)),
    TRIM=ramp((34, 26, 24), (62, 46, 38), (92, 70, 54), (126, 98, 72)),
    WOOD=ramp((48, 38, 30), (88, 72, 54), (122, 102, 74), (154, 132, 96), (184, 160, 118)),
    stone_base=0.54, rim_p=0.85, rivet_p=0.2, moss_thr=0.84, crack=0.2, seed=13, seam_p=0.7,
)


def build():
    F = []

    # ================================================================ 胴: 面の平らな重い樽 + 背びれ + 前垂れ
    T = [ringp(17.0, 9.2, -6.8, 5.4), ringp(20.0, 10.8, -8.2, 6.0), ringp(24.0, 12.2, -9.6, 6.6),
         ringp(28.0, 12.6, -10.0, 6.8), ringp(31.6, 11.4, -8.6, 6.0), ringp(34.0, 6.6, -4.8, 4.4)]
    F += rloft("body", "stone", T, caps=(False, "stone"))
    # 胸: 骨の円盤に核を据える
    F += ellipsoid("body", "bone", (0, 26.0, -9.6), (4.8, 4.8, 1.2), segs=8, rings=1)
    F += ellipsoid("body", "gem", (0, 26.0, -11.4), (2.2, 2.9, 1.3), segs=4, rings=1)
    for dy in (1, -1):
        F += spike("body", "bone", (0, 26.0 + dy * 4.2, -10.4), (0, dy, -0.25), 3.2, 1.1, sides=3, rings=1)
    # 腹の帯 (骨) と前垂れ
    F += rloft("body", "bone", [ringp(21.2, 11.0, -8.6, 6.1), ringp(22.4, 11.2, -8.8, 6.2)], caps=(False, False))
    F += rloft("body", "trim", [ringp(16.6, 9.8, -7.4, 5.8), ringp(18.4, 9.6, -7.2, 5.6)], caps=(False, False))
    F += fbox("body", "stone", (0, 14.8, -8.0), (9.6, 6.6, 1.8), R=rot_x(-10), taper=(0.72, 1.0), cut=0.0)
    F += fbox("body", "bone", (0, 18.2, -7.8), (5.6, 2.0, 1.8), taper=(0.7, 0.8))
    for s in (1, -1):
        F += fbox("body", "stone", (s * 9.6, 15.0, -0.4), (2.0, 6.0, 9.0), R=rot_z(-s * 10), taper=(1.0, 0.75))
    F += rloft("body", "stone", [ringp(32.8, 9.4, -7.0, 6.0), ringp(35.2, 6.4, -5.0, 4.6)], caps=(False, False))
    # 背: 一枚の大きな背びれを 8 つの骨で切った断片
    prof = [3.0, 7.0, 11.0, 14.4, 16.4, 14.4, 10.0, 5.0, 2.0]
    for i in range(8):
        y0 = 17.0 + 2.0 * i
        pts = [(5.4, y0), (5.4 + prof[i], y0 + 0.5), (5.4 + prof[i + 1], y0 + 2.5), (5.4, y0 + 2.0)]
        F += fin(f"spine{i}", "stone", pts, 0.0, 2.2, tip_thin=0.7)
    # 背びれの縁の骨の筋 (中ほどの 4 つ)
    for i in (2, 3, 4, 5):
        y0 = 17.0 + 2.0 * i
        F += spike(f"spine{i}", "bone", (0, y0 + 1.2, 5.6 + prof[i] * 0.7), (0, 0.15, 1.0), 3.6, 0.9, sides=3, rings=1)

    # ================================================================ 頭: 平らな面の兜、横一文字の覗き窓、尾びれの冠、牙
    def hr(y, rx, zf, zb, dz=0.0):
        return ringp(y, rx, zf, zb, 0.0, dz=dz, dzk=(0, 7, 1, 6) if dz else ())
    H = [hr(34.6, 5.4, -4.6, 4.6), hr(36.4, 8.4, -8.8, 7.0), hr(38.6, 8.8, -8.2, 7.2, 0.8), hr(40.6, 8.8, -8.2, 7.2, 0.8),
         hr(41.4, 9.4, -10.4, 7.4), hr(43.6, 8.4, -8.2, 6.8), hr(45.4, 5.4, -4.4, 5.2)]
    F += rloft("head", "stone", H, caps=(False, "stone"), mats=["stone", "stone", "visor", "stone", "stone", "stone"])
    for s in (1, -1):
        # 尾びれの冠: 水平の三日月 2 枚が外へ反り上がる
        wing = [V(s * 0.9, 45.0, -1.4), V(s * 4.4, 45.0, -3.2), V(s * 9.8, 45.0, -2.2), V(s * 14.6, 45.0, 2.0),
                V(s * 11.4, 45.0, 2.4), V(s * 7.6, 45.0, 3.6), V(s * 3.6, 45.0, 5.2), V(s * 0.9, 45.0, 5.6)]
        fw = extrude("head", "bone", wing, (0, 1.8, 0), taper=0.8)
        Rw = rot_z(s * 26)
        transform(fw, Rw, V(0, 45.0, 0) - Rw @ V(0, 45.0, 0))
        F += fw
        F += spike("head", "bone", (s * 5.8, 36.8, -8.6), (s * 0.12, -0.35, -1.0), 5.0, 1.3, sides=4, rings=2, bend=(0, 1.0, 0))
        F += fbox("head", "bone", (s * 6.2, 44.0, -2.6), (3.0, 1.2, 7.0), R=rot_z(-s * 10), taper=(0.7, 0.9))
    F += fbox("head", "bone", (0, 46.0, -2.0), (5.6, 1.6, 8.0), taper=(0.6, 0.9))
    F += fbox("head", "stone", (0, 38.8, -8.6), (1.4, 3.8, 1.0), taper=(1.0, 1.0))

    # ================================================================ 腕: 胸びれの肩
    for s, nm in ((1, "L"), (-1, "R")):
        a, fa, ha = f"arm{nm}", f"forearm{nm}", f"hand{nm}"
        x = s * 14.5
        F += ellipsoid(a, "stone", (x - s * 0.4, 27.0, 0.0), (5.4, 3.2, 5.6), segs=6, rings=1)
        fl = [V(s * 10.6, 30.0, 0.0), V(s * 17.0, 31.0, 0.0), V(s * 22.8, 28.2, 0.0), V(s * 26.4, 22.2, 0.0),
              V(s * 27.4, 15.4, 0.0), V(s * 24.8, 11.4, 0.0), V(s * 22.6, 16.6, 0.0), V(s * 19.6, 22.2, 0.0), V(s * 15.6, 25.2, 0.0),
              V(s * 10.6, 25.6, 0.0)]
        F += extrude(a, "stone", fl, (0, 0, 2.6), taper=0.82)
        # ひれの骨の筋 (放射する 3 本)
        for k, (ex, ey) in enumerate(((25.0, 22.0), (23.4, 17.0), (20.6, 24.6))):
            F += tube(a, "bone", [(s * 15.0, 28.0, 1.6), (s * (ex - 3), (28.0 + ey) / 2, 1.9), (s * ex, ey, 1.9)], ra=[0.9, 0.9, 0.6],
                      rb=[0.5, 0.5, 0.4], sides=3, hint=(0, 0, 1), caps=(False, True))
        F += spike(a, "bone", (s * 24.6, 11.8, 0.0), (s * 0.15, -1.0, 0.0), 3.4, 1.4, sides=4, rings=1)
        F += fbox(a, "stone", (x, 20.4, 0.0), (6.4, 7.4, 6.2), taper=(0.84, 0.86), cut=0.3)
        F += fbox(a, "bone", (x, 17.9, 0.0), (6.8, 1.2, 6.6), taper=(1.0, 1.0))
        F += ellipsoid(fa, "stone", (x, 17.6, 0.6), (3.2, 2.2, 3.2), segs=5, rings=1)
        F += fbox(fa, "stone", (x, 13.8, -0.1), (7.2, 7.0, 6.4), taper=(0.8, 0.82), cut=0.35)
        F += fbox(fa, "bone", (x, 10.9, -0.2), (7.8, 1.0, 7.0), taper=(1.0, 1.0))
        F += spike(fa, "bone", (x + s * 3.0, 14.0, 0.4), (s * 1.0, 0.2, 0.15), 3.8, 1.3, sides=4, rings=1)
        F += fbox(ha, "stone", (x, 8.2, -0.5), (6.6, 4.8, 6.2), taper=(0.82, 0.82), cut=0.4)
        F += fbox(ha, "stone", (x, 5.9, -0.5), (5.2, 1.4, 5.4), taper=(0.9, 0.8))
        for k in range(3):
            F += spike(ha, "tooth", (x + s * 2.0, 9.8, -1.8 + 1.8 * k), (s * 0.7, 1.0, 0.0), 2.2, 0.8, sides=3, rings=1)

    # ================================================================ 脚: 石の柱
    for s, nm in ((1, "L"), (-1, "R")):
        leg = f"leg{nm}"
        x = s * 4.6
        F += fbox(leg, "stone", (x, 9.0, 0.0), (8.6, 6.4, 7.4), taper=(0.86, 0.9), cut=0.3)
        F += fbox(leg, "bone", (x, 5.7, -0.2), (7.2, 1.2, 6.2), taper=(1.0, 1.0))
        F += ellipsoid(leg, "stone", (x, 6.0, -3.2), (3.0, 2.2, 1.8), segs=5, rings=1, rot=rot_x(-12))
        F += fbox(leg, "stone", (x, 3.4, 0.0), (6.8, 5.0, 6.4), taper=(1.12, 1.06), cut=0.3)
        F += rings_along(leg, "stone", [(V(x, 1.4, 3.4), 6.6, 3.0), (V(x, 1.6, -1.0), 8.0, 3.2), (V(x, 0.8, -8.2), 4.6, 1.6)],
                         (1, 0, 0), (0, 1, 0), caps=(True, True))
        F += fbox(leg, "bone", (x, 2.0, -6.0), (6.6, 1.0, 2.0), R=rot_x(-6), taper=(0.7, 1.0))

    # ================================================================ 鉾: 尾びれの三日月 (受け口 socket_main の原点)
    PK = []
    PK += lim("pike", "wood", [(0, 0, 12.6), (0, 0, -12.4)], ra=[1.05, 1.1], rb=[1.05, 1.1], sides=6, phase=30)
    for z in (-10.4, -4.0, 3.0):
        PK += lim("pike", "bone", [(0, 0, z), (0, 0, z - 1.5)], ra=[1.5, 1.5], rb=[1.5, 1.5], sides=6, phase=30)
    PK += fbox("pike", "stone", (0, 0, 13.6), (2.6, 2.6, 2.4), taper=(0.7, 0.7))
    PK += fbox("pike", "stone", (0, 0, -12.8), (3.4, 3.4, 1.4), taper=(0.9, 0.9))
    spear = [(-13.2, 0.0), (-14.6, 2.4), (-21.0, 2.0), (-29.0, 0.0), (-21.4, -1.8), (-14.8, -2.4)]
    PK += fin("pike", "stone", spear, 0.0, 2.2, tip_thin=0.7)
    cres = [(-12.6, -1.6), (-11.8, -7.0), (-13.6, -11.6), (-17.6, -13.8), (-15.4, -9.8), (-16.0, -6.4), (-19.6, -3.4), (-24.0, -2.2),
            (-17.0, -1.4)]
    PK += fin("pike", "bone", cres, 0.0, 2.0, tip_thin=0.55)
    PK += ellipsoid("pike", "gem", (0, 0.4, -12.2), (1.5, 1.5, 1.2), segs=4, rings=1)
    return F, PK, dict(eyes=[dict(x=3.6, y=39.6, a=2.9, b=0.62, tilt=0.16)], extra_paint=extra_paint)


def extra_paint(c, col, glow):
    P, N = c["P"], c["N"]
    # 前垂れの鯨の尾びれの印 (骨色): Y 字
    m0 = (c["bones"] == "body") & (c["mats"] == "stone") & (N[..., 2] < -0.7) & (P[..., 2] < -7.0) & c["owned"]
    ax = np.abs(P[..., 0])
    y = P[..., 1]
    arms = (np.abs(ax - (0.62 * (y - 14.6) + 0.4)) < 0.42) & (y > 14.6) & (y < 18.0)
    stem = (ax < 0.45) & (y > 12.8) & (y < 14.8)
    g = m0 & (arms | stem) & (y < 18.2)
    col = np.where(g[..., None], BONE_PIX[3], col)
    return col, glow


BONE_PIX = PAL["BONE"]
