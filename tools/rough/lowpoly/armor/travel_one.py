def sleeve(ab, s, mat, top=23.6, bot=13.0, w=4.8, d=4.9):
    return bx(ab, mat, (s * 6.0, (top + bot) / 2, 0), (w, top - bot, d), taper=(0.98, 0.98), skip=("u",))


def wrap_rings(b, cx, y0, y1, n, r=2.55, mat="cloth", d=2.65):
    out = []
    for i in range(n):
        y = y0 + (y1 - y0) * (i + 0.5) / n
        out += bx(b, mat, (cx, y, 0), (2 * r, (y1 - y0) / n * 0.8, 2 * d), rot=rot_z(6 if i % 2 else -6), skip=("u", "b"))
    return out


