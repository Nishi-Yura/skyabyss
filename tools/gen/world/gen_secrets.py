#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""隠れた発見の置き場 (2026-11-03。Wynncraft の Secret Discoveries。docs/design/40 の 6 章「隠れた発見」)。

    PYTHONIOENCODING=utf-8 python -I tools/gen/world/gen_secrets.py

土地ごと (都のまわり・岩鯨・潮殻・雷翼・余燼) に PER_REGION か所。はじまりの島には置かない (島へは戻れないので、見落とすと二度と見つけられない)。道・町・都・見どころ・巨神の居場所・祠・跡地から離れた陸の、
まわりの高さの差が大きい所 (崖の下・丘の肩) を選ぶ。互いに MIN_GAP 以上離す。種類は土地の色に合わせて回す。
書くもの: src/main/resources/data/skyabyss/continent/secrets.json ({id, region, kind, x, z} の並び。id は書いた順の番号)
"""
import gzip
import json
import math
import os
import struct

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(ROOT, 'src', 'main', 'resources', 'data', 'skyabyss', 'continent')
PER_REGION = 4
MIN_GAP = 220
# 土地の番号 (ContinentMap.MEADOW..EMBER) → 名前と、置く種類の順
REGIONS = {0: 'meadow', 2: 'whale', 3: 'tide', 4: 'storm', 5: 'ember'}
KINDS = {
    'meadow': ['moss_shrine', 'old_camp', 'buried_head', 'bell_shard'],
    'whale': ['bone_tip', 'moss_shrine', 'buried_head', 'old_camp'],
    'tide': ['shell_cairn', 'old_camp', 'buried_head', 'bone_tip'],
    'storm': ['rod_stub', 'moss_shrine', 'bone_tip', 'old_camp'],
    'ember': ['ash_idol', 'bone_tip', 'old_camp', 'buried_head'],
}


def load(name):
    raw = gzip.open(os.path.join(D, name)).read()
    assert raw[:4] == b'SKCN'
    size, scale, ox, oz = struct.unpack('>iiii', raw[4:20])
    return size, scale, ox, oz, raw[20:]


def main():
    size, scale, ox, oz, H = load('height.bin')
    _, _, _, _, RG = load('region.bin')
    lay = json.load(open(os.path.join(D, 'layout.json'), encoding='utf-8'))
    lairs = json.load(open(os.path.join(D, 'lairs.json'), encoding='utf-8'))
    pois = json.load(open(os.path.join(D, 'pois.json'), encoding='utf-8'))
    segs = [(a, b) for line in lay['roads'] for a, b in zip(line, line[1:])]

    def cell(x, z):
        i = (x - ox) // scale
        j = (z - oz) // scale
        if not (0 <= i < size and 0 <= j < size):
            return None
        return j * size + i

    def h(x, z):
        c = cell(x, z)
        return 0 if c is None else H[c]

    def region(x, z):
        c = cell(x, z)
        return None if c is None else RG[c]

    def road(x, z):
        best = 1e9
        for a, b in segs:
            if min(abs(a[0] - x), abs(b[0] - x)) > 400 and min(abs(a[1] - z), abs(b[1] - z)) > 400:
                continue
            dx = b[0] - a[0]
            dz = b[1] - a[1]
            l2 = dx * dx + dz * dz
            u = 0 if l2 == 0 else max(0, min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / l2))
            best = min(best, math.hypot(x - (a[0] + u * dx), z - (a[1] + u * dz)))
        return best

    keep = [(lay['capital'], 240)] + [(p, 150) for p in lay['towns'].values()] + [(p, 200) for p in lay['sites'].values()]
    keep += [((p['x'], p['z']), 70) for p in pois]
    keep += [((v['x'], v['z']), 120) for k, v in lairs.items() if isinstance(v, dict) and 'x' in v]
    keep += [(p, 70) for p in lairs['shrines'].values()]
    keep += [(lay['start'], 90), (lay['dock'], 70)]
    for f in lay.get('ferry_docks', []):
        keep += [(p, 60) for p in f]

    found = []
    for rid, rname in REGIONS.items():
        cands = []
        for x in range(ox + 64, ox + size * scale - 64, 24):
            for z in range(oz + 64, oz + size * scale - 64, 24):
                if region(x, z) != rid:
                    continue
                y = h(x, z)
                if y <= 66:
                    continue
                around = [h(x + dx, z + dz) for dx in (-12, 0, 12) for dz in (-12, 0, 12)]
                if min(around) <= 64:
                    continue
                if any(math.hypot(x - p[0], z - p[1]) < r for p, r in keep):
                    continue
                d = road(x, z)
                if d < 35 or d > 260:
                    continue
                # 崖の下・丘の肩: まわりの差が大きいほど。道から見つけられる遠さ (40〜120) を少し好む
                relief = max(around) - min(around)
                score = relief + (8 if 40 <= d <= 120 else 0) + (x * 7 + z * 13) % 5 * 0.1
                cands.append((score, x, z))
        cands.sort(reverse=True)
        picked = []
        for score, x, z in cands:
            if all(math.hypot(x - q[0], z - q[1]) >= MIN_GAP for q in picked + [(f['x'], f['z']) for f in found]):
                picked.append((x, z))
            if len(picked) >= PER_REGION:
                break
        for i, (x, z) in enumerate(picked):
            found.append({'id': len(found), 'region': rname, 'kind': KINDS[rname][i % len(KINDS[rname])], 'x': x, 'z': z})
        print(rname, len(picked), picked)
    out = os.path.join(D, 'secrets.json')
    with open(out, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'hidden discoveries (world/continent/ContinentSecrets). Generated by tools/gen/world/gen_secrets.py', 'secrets': found},
                  f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('wrote', out, len(found))


if __name__ == '__main__':
    main()
