#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""巡り路の野営地の置き場 (2026-11-03。Wynncraft のルートランの野営地。docs/design/54 の 3.1.1)。

    PYTHONIOENCODING=utf-8 python -I tools/gen/world/gen_camps.py

土地 (鯨見・汐守・風待・灰炉) ごとに一つ。町から TOWN_MIN〜TOWN_MAX、道から ROAD_MIN〜ROAD_MAX (道から見えて行ける、道の上ではない) の、
平らな陸 (±8 の高さの差が FLAT 以下) で、見どころ・巨神の居場所・祠・跡地・隠れた発見から離れた所。平らで、道から 40 ほどの所を選ぶ。
書くもの: src/main/resources/data/skyabyss/continent/camps.json ({id, region, x, z} の並び。id は土地の名前)
"""
import gzip
import json
import math
import os
import struct

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(ROOT, 'src', 'main', 'resources', 'data', 'skyabyss', 'continent')
LANDS = {2: 'whale', 3: 'tide', 4: 'storm', 5: 'ember'}
TOWN_MIN, TOWN_MAX = 110, 260
ROAD_MIN, ROAD_MAX = 25, 60
FLAT = 3


def load(name):
    raw = gzip.open(os.path.join(D, name)).read()
    assert raw[:4] == b'SKCN'
    size, scale, ox, oz = struct.unpack('>iiii', raw[4:20])
    return size, scale, ox, oz, raw[20:]


def main():
    size, scale, ox, oz, H = load('height.bin')
    _, _, _, _, RG = load('region.bin')
    lay = json.load(open(os.path.join(D, 'layout.json'), encoding='utf-8'))
    lairs = json.load(open(os.path.join(D, 'lairs.json'), encoding='utf-8'))
    pois = json.load(open(os.path.join(D, 'pois.json'), encoding='utf-8'))
    secrets = json.load(open(os.path.join(D, 'secrets.json'), encoding='utf-8'))['secrets']
    segs = [(a, b) for line in lay['roads'] for a, b in zip(line, line[1:])]

    def cell(x, z):
        i = (x - ox) // scale
        j = (z - oz) // scale
        return j * size + i if 0 <= i < size and 0 <= j < size else None

    def h(x, z):
        c = cell(x, z)
        return 0 if c is None else H[c]

    def region(x, z):
        c = cell(x, z)
        return None if c is None else RG[c]

    def road(x, z):
        best = 1e9
        for a, b in segs:
            dx, dz = b[0] - a[0], b[1] - a[1]
            l2 = dx * dx + dz * dz
            u = 0 if l2 == 0 else max(0, min(1, ((x - a[0]) * dx + (z - a[1]) * dz) / l2))
            best = min(best, math.hypot(x - (a[0] + u * dx), z - (a[1] + u * dz)))
        return best

    keep = [(lay['capital'], 240)] + [(p, 150) for p in lay['sites'].values()]
    keep += [((p['x'], p['z']), 90) for p in pois]
    keep += [((v['x'], v['z']), 140) for k, v in lairs.items() if isinstance(v, dict) and 'x' in v]
    keep += [(p, 80) for p in lairs['shrines'].values()]
    keep += [((s['x'], s['z']), 60) for s in secrets]
    out = []
    for rid, land in LANDS.items():
        town = lay['towns'][land]
        cands = []
        for x in range(town[0] - TOWN_MAX, town[0] + TOWN_MAX + 1, 6):
            for z in range(town[1] - TOWN_MAX, town[1] + TOWN_MAX + 1, 6):
                d_town = math.hypot(x - town[0], z - town[1])
                if not TOWN_MIN <= d_town <= TOWN_MAX or region(x, z) != rid:
                    continue
                y = h(x, z)
                around = [h(x + dx, z + dz) for dx in (-8, 0, 8) for dz in (-8, 0, 8)]
                if y <= 67 or min(around) <= 66 or max(around) - min(around) > FLAT:
                    continue
                if any(math.hypot(x - p[0], z - p[1]) < r for p, r in keep):
                    continue
                d = road(x, z)
                if not ROAD_MIN <= d <= ROAD_MAX:
                    continue
                score = -(max(around) - min(around)) * 3 - abs(d - 40) * 0.2 - abs(d_town - 170) * 0.02
                cands.append((score, x, z, round(d), round(d_town)))
        cands.sort(reverse=True)
        if not cands:
            raise SystemExit(f'no camp spot in {land}')
        s, x, z, d, dt = cands[0]
        out.append({'id': land, 'region': rid, 'x': x, 'z': z})
        print(land, (x, z), 'road', d, 'town', dt)
    path = os.path.join(D, 'camps.json')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'circuit (lootrun) camps (endgame/CircuitCamps). Generated by tools/gen/world/gen_camps.py', 'camps': out},
                  f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
