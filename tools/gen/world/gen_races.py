#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""早駆けの道の道筋 (2026-11-03。docs/design/38 の 8 章「早駆けの道」)。

    PYTHONIOENCODING=utf-8 python -I tools/gen/world/gen_races.py

土地ごとに一本、道 (layout.json の roads) の上を走る道筋を作る。町・都の門から GATE_SKIP だけ外から始め、
終わりの手前 END_SKIP で終える。STEP ごとに関所 (通り抜ける輪) を置く。標 (始まりの柱) は始まりの関所から道の右へ POST_SIDE。
書くもの: src/main/resources/data/skyabyss/continent/races.json ({id, region, road, post, checkpoints, length} の並び)
"""
import json
import math
import os

ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), '..', '..', '..'))
D = os.path.join(ROOT, 'src', 'main', 'resources', 'data', 'skyabyss', 'continent')
STEP = 48
GATE_SKIP = 18
END_SKIP = 14
POST_SIDE = 6
# (id, 土地, 道の番号) 都の北門から鯨見へ・都の西門から風待へ・灰炉から東へ・汐守から北へ・鯨見から東へ
COURSES = [
    ('whale_road', 'meadow', 1),
    ('storm_road', 'storm', 3),
    ('ember_east', 'ember', 6),
    ('tide_north', 'tide', 7),
    ('whale_east', 'whale', 2),
]


def resample(line, step):
    """折れ線の上を、始まりから step ごとの点 (終わりの点も入れる)"""
    out = [tuple(line[0])]
    left = step
    for a, b in zip(line, line[1:]):
        seg = math.dist(a, b)
        t = 0.0
        while seg - t >= left:
            t += left
            u = t / seg
            out.append((a[0] + (b[0] - a[0]) * u, a[1] + (b[1] - a[1]) * u))
            left = step
        left -= seg - t
    if math.dist(out[-1], line[-1]) > step * 0.3:
        out.append(tuple(line[-1]))
    else:
        out[-1] = tuple(line[-1])
    return out


def trim(line, start, end):
    """折れ線の始まりから start、終わりから end を切り落とす"""
    def cut_front(pts, d):
        while len(pts) >= 2:
            seg = math.dist(pts[0], pts[1])
            if seg > d:
                u = d / seg
                pts[0] = (pts[0][0] + (pts[1][0] - pts[0][0]) * u, pts[0][1] + (pts[1][1] - pts[0][1]) * u)
                return pts
            d -= seg
            pts.pop(0)
        return pts
    pts = cut_front([tuple(p) for p in line], start)
    pts = cut_front(pts[::-1], end)[::-1]
    return pts


def main():
    lay = json.load(open(os.path.join(D, 'layout.json'), encoding='utf-8'))
    out = []
    for cid, region, road in COURSES:
        line = trim(lay['roads'][road], GATE_SKIP, END_SKIP)
        cps = resample(line, STEP)
        length = sum(math.dist(a, b) for a, b in zip(cps, cps[1:]))
        a, b = cps[0], cps[1]
        dx, dz = b[0] - a[0], b[1] - a[1]
        n = math.hypot(dx, dz)
        # 進む向きの右 (x, z の平面で (-dz, dx))
        post = (a[0] - dz / n * POST_SIDE, a[1] + dx / n * POST_SIDE)
        out.append({'id': cid, 'region': region, 'road': road, 'post': [round(post[0]), round(post[1])],
                    'checkpoints': [[round(x), round(z)] for x, z in cps], 'length': round(length)})
        print(cid, len(cps), 'checkpoints', round(length), 'blocks')
    path = os.path.join(D, 'races.json')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        json.dump({'_comment': 'race courses on the roads (world/continent/RaceCourses). Generated by tools/gen/world/gen_races.py', 'courses': out},
                  f, ensure_ascii=False, indent=1)
        f.write('\n')
    print('wrote', path)


if __name__ == '__main__':
    main()
