"""関節の見た目の確認用の台本 tools/shots/joints.txt を書く (確認の絵は tools/sheets/joints_sheet.py が組む)。
モブを目の前の決まった位置 (0, 地面, 0) に出し、体の高さに合わせた距離・高さのカメラで、休め (rest) と動作の最大付近 (pose) を撮る。
使い方: python -I tools/gen/shots/gen_joints_shots.py → ./gradlew runShots --no-daemon -Pscript=tools/shots/joints.txt → python -I tools/sheets/joints_sheet.py
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
# (id, 高さ (ブロック), 足元の y, 動作, 動作を流してから撮るまでの tick, 浮かせるか)
MODELS = [
    ("bone_sentinel", 2.2, -60, "pounce", 8, False),
    ("whalebone_captain", 3.2, -60, "slam", 12, False),
    ("static_moth", 1.0, -59.3, "attack", 8, True),
    ("moss_crawler", 1.5, -60, "pounce", 8, False),
    ("elder_sentry", 2.3, -60, "attack", 8, False),
    ("thunder_supplicant", 2.3, -60, "attack", 8, False),
    ("elder_sentinel", 2.9, -60, "pounce", 8, False),
]


def main():
    L = ["# Generated by tools/gen/shots/gen_joints_shots.py: joint look check (rest / max pose), mobs placed at a fixed spot in front of the camera",
         "world shots flat", "size 960 540", "timeout 900", "render 8", "clouds off",
         "cmd skyabyss cinematic stop", "cmd time set noon", "cmd weather clear", "cmd gamemode spectator",
         "cmd fill -30 -61 -30 30 -61 30 minecraft:smooth_basalt destroy", "hud off", "lowpoly on", "fov 50"]
    for mid, h, y, anim, tick, fly in MODELS:
        d = max(1.7, 1.5 * h)
        cx, cz = round(d * 0.7, 2), round(d * 0.7, 2)
        cy = round(y + h * 0.5 - 1.62, 2)
        nog = "NoGravity:1b," if fly else ""
        L += [f"# --- {mid}", "cmd kill @e[type=!minecraft:player,distance=..80]",
              f"cmd summon skyabyss:{mid} 0 {y} 0 {{NoAI:1b,{nog}Rotation:[0f,0f],PersistenceRequired:1b,Invulnerable:1b,Tags:[\"m\"]}}",
              f"camera minecraft:overworld {cx} {cy} {cz} 135 0", "waitchunks", "wait 120",
              f"shot j_{mid}_rest", f"cmd skyabyss dev anim @e[tag=m] {anim}"]
        L += [f"wait {tick}", f"shot j_{mid}_pose_a", "wait 4", f"shot j_{mid}_pose_b"]
        L += ["wait 40"]
    out = ROOT / "tools/shots/joints.txt"
    out.write_text("\n".join(L) + "\n", encoding="utf-8")
    print(out)


main()
