def build(key, cfg):
    script = "lp_titan_" + key
    e = cfg["entity"]
    s = HEAD.format(title="titan body " + key, script=script, time=cfg["time"])
    s += cfg["summon"]
    s += "hud off\ncmd gamemode spectator\n"
    for pre, mode in (("lp_titan_%s_" % key, "on"), ("cubes_titan_%s_" % key, "off")):
        s += "lowpoly %s\nwait 30\n" % mode
        for name, pos, target, ground, wait, render in cfg["views"]:
            if ground:  # feet on the standing plane
                pos = (pos[0], cfg["ground"], pos[2])
            if render:
                s += "render %d\n" % render
            s += tp(e, pos, target)
            s += "wait %d\nshot %s%s\n" % (wait, pre, name)
            if render:
                s += "render 16\n"
        # frame time with the body filling the view
        s += tp(e, cfg["perf"], cfg["perf_target"])
        s += "wait 120\nperf 300 %s_%s_a\nperf 300 %s_%s_b\n" % (key, mode, key, mode)
    s += "lowpoly on\nquit\n"
    path = os.path.join(PATH, script + ".txt")
    with open(path, "w", encoding="utf-8") as f:
        f.write(s)
    print("wrote", path)


if __name__ == "__main__":
    for k, c in (("whale", WHALE), ("tide", TIDE), ("storm", STORM), ("ember", EMBER)):
        build(k, c)
