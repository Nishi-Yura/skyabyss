def main():
    img = Image.new("RGBA", (8 * len(ICONS), 8), (0, 0, 0, 0))
    for i, rows in enumerate(ICONS):
        assert len(rows) == 8, i
        for y, row in enumerate(rows):
            row = row.ljust(8, ".")[:8]
            for x, ch in enumerate(row):
                img.putpixel((i * 8 + x, y), PAL.get(ch, PAL["."]))
    os.makedirs(os.path.dirname(OUT), exist_ok=True)
    img.save(OUT)
    print("wrote", os.path.normpath(OUT), len(ICONS), "icons")


if __name__ == "__main__":
    main()
