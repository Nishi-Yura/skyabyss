def eye(m, bone, c, r, d, iris, glow=False, lid=(20, 20, 24)):
    """目の玉と、アトラスに描く瞳 (mlp.eye_paint)"""
    c = np.asarray(c, float)
    m.add(f"eye{len(m.eyes)}", ell(bone, "eye", c, (r, r, r), segs=8, rings=2))
    m.eyes.append(dict(c=c, r=r * 1.08, dir=tuple(nrm(np.asarray(d, float))), a=r * 0.8, b=r * 0.8, bone=bone, iris=iris, lid=lid, pa=0.5, pb=0.5, glow=glow))


def export_named(m, name, size, atlas, glow, out_dir):
    out_dir = Path(out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)
    Image.fromarray(atlas, "RGBA").save(out_dir / f"{name}_atlas.png")
    gm = np.zeros((size, size, 4), np.uint8)
    gm[glow] = (255, 255, 255, 255)
    has_glow = bool(glow.any())
    if has_glow:
        Image.fromarray(gm, "RGBA").save(out_dir / f"{name}_glowmask.png")
    bs = {b: {"vertices": [], "uvs": [], "triangles": []} for b in m.bones}
    for f in m.F:
        b = bs[f.bone]
        base = len(b["vertices"])
        cen = f.uv.mean(0)
        for p, uv in zip(f.verts, f.uv):
            d = cen - uv
            nn = np.linalg.norm(d)
            uv = uv + d / nn * min(mlp.INSET, nn * 0.4) if nn > 1e-9 else uv
            b["vertices"].append([round(float(x) + 0.0, 4) for x in p])
            b["uvs"].append([round(float(uv[0]) / size, 5), round(float(uv[1]) / size, 5)])
        for a, c, d in f.tris():
            b["triangles"].append([base + a, base + c, base + d])
    tot, out = 0, {}
    for k, (parent, pivot) in m.bones.items():
        b = bs[k]
        b["triangle_count"] = len(b["triangles"])
        tot += b["triangle_count"]
        out[k] = {"parent": parent, "pivot": [float(x) for x in pivot], **b}
    data = {"format_version": 1, "name": name, "units": "1/16 block, y up, front = -Z",
            "uv": "normalized, origin top-left (v down)", "texture": f"{name}_atlas.png", "texture_size": [size, size],
            "texels_per_unit": TEX, "uv_inset_texels": mlp.INSET, "triangle_count": tot,
            "note": "dungeon boss (docs/design/55). Generated by tools/gen/mobs/dungeon_bosses_lp/" + m.id + ".py", "bones": out}
    (out_dir / f"{name}_mesh.json").write_text(json.dumps(data, ensure_ascii=False), encoding="utf-8")
    return data, has_glow


def cube_geo_named(m, name, path, bounds_w=8, bounds_h=6):
    bounds = {}
    for f in m.F:
        lo, hi = bounds.get(f.bone, (np.full(3, 1e9), np.full(3, -1e9)))
        bounds[f.bone] = (np.minimum(lo, f.verts.min(0)), np.maximum(hi, f.verts.max(0)))
    bones = []
    for k, (parent, pivot) in m.bones.items():
        b = {"name": k, "pivot": [round(float(x), 4) for x in pivot]}
        if parent:
            b["parent"] = parent
        if k in bounds:
            lo, hi = bounds[k]
            o = [-float(hi[0]), float(lo[1]), float(lo[2])]
            s = [float(hi[0] - lo[0]), float(hi[1] - lo[1]), float(hi[2] - lo[2])]
            b["cubes"] = [{"origin": [round(x, 3) for x in o], "size": [round(max(x, 0.01), 3) for x in s], "uv": [0, 0]}]
        bones.append(b)
    geo = {"format_version": "1.12.0", "minecraft:geometry": [{
        "description": {"identifier": "geometry." + name, "texture_width": 16, "texture_height": 16,
                        "visible_bounds_width": bounds_w, "visible_bounds_height": bounds_h, "visible_bounds_offset": [0, bounds_h / 3, 0]},
        "bones": bones}]}
    Path(path).write_text(json.dumps(geo, ensure_ascii=False, indent=1), encoding="utf-8")


def write_anims(gaits, name, path):
    data = {"format_version": "1.8.0", "animations": {f"animation.{name}.{g.name}": g.to_json() for g in gaits}}
    Path(path).write_text(json.dumps(data, ensure_ascii=False, indent=1), encoding="utf-8")


def keys(name, length, frames, hold=False):
    """一度だけの動き。frames = [(時刻, {骨: {"rot": (x,y,z), "pos": (x,y,z)}})]。抜けた骨・抜けた時刻は 0 にそろえる"""
    g = Gait(name, length, loop=("hold_on_last_frame" if hold else False))
    g.length = length
    bones = {}
    for _, pose in frames:
        for b, ch in pose.items():
            for k in ch:
                bones.setdefault(b, set()).add(k)
    g.keys = {}
    for b, chans in bones.items():
        g.keys[b] = {}
        for k in chans:
            kv = {}
            for t, pose in frames:
                kv[t] = tuple(pose.get(b, {}).get(k, (0.0, 0.0, 0.0)))
            g.keys[b][k] = kv
    return g


def install(m, name, size, atlas, glow, gaits, bounds=(8, 6)):
    out = WORK / m.id
    data, has_glow = export_named(m, name, size, atlas, glow, out)
    cube_geo_named(m, name, ASSETS / "geo/entity" / (name + ".geo.json"), *bounds)
    avg = atlas[..., :3][atlas[..., 3] > 0].mean(0).astype(np.uint8)
    Image.new("RGBA", (16, 16), tuple(int(x) for x in avg) + (255,)).save(ASSETS / "textures/entity" / (name + ".png"))
    cmd = [sys.executable, str(ROOT / "tools/install/install_lowpoly.py"), name, "--mesh", str(out / f"{name}_mesh.json"),
           "--atlas", str(out / f"{name}_atlas.png")]
    if has_glow:
        cmd += ["--glow", str(out / f"{name}_glowmask.png")]
    subprocess.check_call(cmd, cwd=str(ROOT))
    write_anims(gaits, name, ASSETS / "animations/entity" / (name + ".animation.json"))
    return data


def sheet(m, atlas, glow, gaits, name, info, poses=()):
    """前・斜め・横・後ろと、動きの姿勢 (poses = [(動きの名前, 時刻)])"""
    F = voxel.font
    cen, sc = np.array(m.view["center"], float), m.view["scale"]
    PW, PH = 360, 300
    views = [(180, 8), (215, 16), (270, 6), (330, 24)]
    row1 = [view(m.F, atlas, glow, yaw, pitch, (PW, PH), cen, sc) for yaw, pitch in views]
    by = {g.name: g for g in gaits}
    row2 = []
    for gname, t in poses:
        g = by[gname]
        faces = posed(m, g.pose_at(t, 0.0))
        row2.append((f"{gname} {t:.2f}s", view(faces, atlas, glow, 225, 14, (PW, PH), cen, sc)))
    cols = 4
    rows2 = (len(row2) + cols - 1) // cols
    W_ = 20 + cols * (PW + 10)
    H_ = 90 + PH + 20 + rows2 * (PH + 34) + 20
    cv = Image.new("RGB", (W_, H_), (16, 16, 22))
    d = ImageDraw.Draw(cv)
    d.text((20, 14), f"{m.title}（{name}）", font=F(28), fill=(236, 232, 218))
    d.text((20, 52), "  ".join(f"{k} {v}" for k, v in info.items()), font=F(15), fill=(176, 176, 192))
    for i, im in enumerate(row1):
        cv.paste(im, (20 + i * (PW + 10), 90))
    y = 90 + PH + 20
    for i, (label, im) in enumerate(row2):
        x = 20 + (i % cols) * (PW + 10)
        yy = y + (i // cols) * (PH + 34)
        d.text((x, yy), label, font=F(16), fill=(150, 232, 255))
        cv.paste(im, (x, yy + 24))
    REVIEW.mkdir(parents=True, exist_ok=True)
    cv.save(REVIEW / f"{name}_sheet.png")
