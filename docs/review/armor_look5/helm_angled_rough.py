# 薄い土台（頭 +1.4）＋ 3 軸に傾けた大きな部品で輪郭を作る兜の 3 案。数値を出すだけ。
import json, math, os, sys
_d = os.path.dirname(os.path.abspath(__file__))
_src = open(os.path.join(_d, 'helms2.py'), encoding='utf8').read()
_src = _src[:_src.index("H = {}")]
_argv = sys.argv; sys.argv = [_argv[0], _argv[1]]
exec(_src)
OUT = _argv[1]
E = 9.4   # 薄い土台の半幅（頭 8 + 1.4）
Y0, Y1 = 46.8, 65.4


def shell(face=None):
    """薄い土台。face=(x0,x1,y0,y1) なら前に顔の窓をあける"""
    if face is None:
        return [box('sh', [-E, Y0, -E], [E, Y1, E])]
    x0, x1, y0, y1 = face
    return [box('sh_b', [-E, Y0, -E + 2.0], [E, Y1, E]),
            box('sh_ft', [-E, y1, -E], [E, Y1, -E + 1.4]), box('sh_fb', [-E, Y0, -E], [E, y0, -E + 1.4]),
            box('sh_fr', [x1, y0, -E], [E, y1, -E + 1.4]), box('sh_fl', [-E, y0, -E], [x0, y1, -E + 1.4])]


def rot(name, f, t, r, o):
    return box(name, f, t, r, o)


H = {}

# R1 V 字の面頬（前へ尖る二枚の板・横の息穴・頂の菱形の飾り）
v = [rot('v_up', [0, 52.6, -11.6], [10.6, 63.4, -10], [-12, -34, 0], [0, 58, -11]),
     rot('v_lo', [0, 45.4, -11.6], [9.6, 52.4, -10], [16, -30, 0], [0, 52.5, -11])]
v += [rot(f'd_v_s{i}', [2.2 + 2.2 * i, 49.0, -11.9], [3.4 + 2.2 * i, 51.6, -11.5], [16, -30, 0], [0, 52.5, -11]) for i in range(3)]
v += [rot('d_v_eye', [1.6, 55.6, -11.9], [9.2, 57.0, -11.5], [-12, -34, 0], [0, 58, -11]),
      rot('b_v_edge', [0, 63.2, -11.9], [10.8, 64.4, -10.2], [-12, -34, 0], [0, 58, -11])]
H['R1_visor'] = (shell() + v + mirror(v) +
                 [box('b_ridge', [-0.8, 45.6, -13.4], [0.8, 64.6, -11.4], [-6, 0, 0], [0, 55, -12]),
                  rot('crest', [-4.2, 64, -4.2], [4.2, 72.4, 4.2], [35, 45, 0], [0, 68.2, 0]),
                  rot('g_crest', [-1.6, 70.6, -1.6], [1.6, 73.8, 1.6], [35, 45, 0], [0, 72.2, 0])])

# R2 菱形の額縁（顔を囲む大きな菱形が頭の輪郭をはみ出す・頂に宝石・左右に小さな翼）
fr = [rot('fr_ur', [-1.6, 58, -13.2], [1.6, 74, -10.2], [0, 0, -45], [0, 58, -11.7])]
fr = []
R = 14.4; cy = 57.6
corners = [(0, cy + R), (R, cy), (0, cy - R * 0.8), (-R, cy)]
for i in range(4):
    a, b = corners[i], corners[(i + 1) % 4]
    fr.append(bar(f'fr{i}', (a[0], a[1], -11.4), (b[0], b[1], -11.4), 3.0, 3.2))
    fr.append(bar(f'b_fri{i}', (a[0] * 0.78, cy + (a[1] - cy) * 0.78, -12.4), (b[0] * 0.78, cy + (b[1] - cy) * 0.78, -12.4), 0.8, 1.0))
wing = [rot('wg', [9.4, 58, -6], [11, 70, 4], [0, 0, -28], [10, 58, 0]), rot('wg2', [9.4, 56, -2], [10.8, 64, 6], [0, 0, -50], [10, 56, 2])]
H['R2_diamond'] = (shell((-5.4, 5.4, 48.4, 59.6)) + fr + wing + mirror(wing) +
                   [rot('g_gem', [-2.2, cy + R - 2.2, -13.4], [2.2, cy + R + 2.2, -10.4], [0, 0, 45], [0, cy + R, -11.9]),
                    box('b_brow', [-5.8, 59.6, -10.4], [5.8, 60.8, -9.2])])

# R3 後ろへ流れる刃（額の嘴・こめかみから後ろ上へ長い刃・頬当て）
bl = chain('bl', [(8.6, 61, -4), (13, 66, 4), (16, 71, 13), (17, 74, 21)], 4.4, 2.0)
bl += chain('bm', [(9.2, 56, 0), (14, 58.6, 8), (17.4, 60, 16)], 2.6, 1.4)
ch = [rot('cheek', [6, 47.4, -12.2], [10.2, 56.6, -10.6], [8, -22, 0], [8, 56, -11]),
      rot('b_cheek', [6, 47.0, -12.5], [10.4, 48.0, -10.6], [8, -22, 0], [8, 56, -11])]
H['R3_swept'] = (shell((-6, 6, 50, 56.6)) + bl + mirror(bl) + ch + mirror(ch) +
                 [rot('beak', [-6.6, 56.4, -16.4], [6.6, 58.2, -9], [-22, 0, 0], [0, 58, -9.4]),
                  rot('beak2', [-3.4, 56.6, -19.6], [3.4, 58.2, -15.4], [-30, 0, 0], [0, 58, -15.6]),
                  rot('b_bkline', [-0.6, 58.0, -19.0], [0.6, 59.0, -9.4], [-22, 0, 0], [0, 58, -9.4]),
                  box('b_top', [-0.8, 65.4, -8], [0.8, 67, 9])])

os.makedirs(OUT, exist_ok=True)
for k, v in H.items():
    names = [e['name'] for e in v]
    assert len(names) == len(set(names)), k
    json.dump(v, open(f'{OUT}/{k}.json', 'w'), separators=(',', ':'))
    print(k, len(v))
